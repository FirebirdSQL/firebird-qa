def fetch_as_str(cur, sql):
    cur.execute(sql)
    return [ tuple(None if v is None else str(v) for v in row) for row in cur.fetchall() ]

@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action):
    act.isql(switches=['-q'], input=DDL, combine_output=True)
    assert act.return_code == 0, act.stdout
    act.reset()

    with act.db.connect() as con:
        cur = con.cursor()
        for i, (sql, expected) in enumerate(CHK_LIST, 1):
            got = fetch_as_str(cur, sql)
            assert got == expected, (
                f'query #{i} mismatch\n'
                f'SQL:\n{sql}\n'
                f'expected: {expected}\n'
                f'got:      {got}'
            )

        # 11. TVF can NOT follow LATERAL keyword directly (must be wrapped in derived table).
        # If parser starts to accept this then following assert will fail and this test
        # (together with its description) must be updated:
        bad_sql = """
            select t.id, u.v
            from perm_t t
            cross join lateral unlist(t.csv returning int) u(v)
            order by t.id
        """
        raised = None
        try:
            ps, rs = None, None
            try:
                ps = cur.prepare(bad_sql)
                rs = cur.execute(ps)
                rows = rs.fetchall()
            except DatabaseError as e:
                raised = e
            finally:
                if rs:
                    rs.close()
                if ps:
                    ps.free()
        except Exception as e:
            raised = e

        assert raised is not None, (
            'Parser now accepts TVF directly after LATERAL keyword: '
            'this test and its description have to be updated!'
        )
        print('TVF directly after LATERAL, expectedly failed with:', raised.__str__().replace('\n', ' '))
