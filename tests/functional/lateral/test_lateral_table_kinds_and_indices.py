"""
ID:          functional.lateral.test_lateral_table_kinds_and_indices
ISSUE:       CORE-3435
TITLE:       LATERAL join against every kind of tables (except external) with indices present /
             inactive / absent
DESCRIPTION:
    [generated by zcode.ai]
    Verifies that results of lateral join queries remain the same for all kinds of DB tables:
        * permanent table;
        * global temporary table (GTT), both ON COMMIT PRESERVE ROWS and ON COMMIT DELETE ROWS;
        * local temporary table (LTT, #8860);
        * packaged temporary table (PTT, public/header and private/body via procedures,
          #8974, PR #8983);
        * declared local temporary table inside PSQL (DTT, PR #9058).
    For permanent, GTT and LTT each of THREE index states is checked:
        1) index PRESENT (created and active);
        2) index INACTIVE ('alter index ... inactive');
        3) index ABSENT ('alter index ... active' + 'drop index').
    For PTT and DTT only states 'present' and 'absent' are checked: currently
    'alter index <idx> [in]active' fails for indices of packaged temporary tables
    ("Index not found" although the index IS visible in RDB$INDICES with RDB$PACKAGE_NAME set)
    and for indices that are declared within DTT statements (these are connection-local and
    are not accessible via DDL at all).

    Each kind is checked with three queries:
        Q1: cross join lateral, correlated aggregate (count + sum of peers excluding self);
        Q2: cross join lateral with 'order by ... fetch first 1 rows only' (max val pickup);
        Q3: cross join lateral with 'order by ... offset 1 row fetch next 1 rows only'
            (second-highest val; for group with single row this produces NO lateral row at
            all, so the outer row is dropped by cross join - unlike Q1 where aggregate
            without GROUP BY always returns exactly one row).
    Expected values are computed from the dataset by the test itself.

    Additionally, transaction-scoped data visibility through lateral is checked for
    ON COMMIT DELETE ROWS GTT: its rows must be visible inside the lateral query before
    commit and disappear from it after commit.

    Unlike tests core_3435_test.py / gh_8628_test.py / s13 (named_windows) / gh_8061_postfix_test.py,
    correlation is expressed only in WHERE clauses of lateral derived tables; no unions of
    outer-referencing selects, no window functions, no self-recursive lateral joins.
NOTES:
    [20.11.2026] pzotov / AI assistant
    See also:
        LTT:  https://github.com/FirebirdSQL/firebird/pull/8860
        PTT:  https://github.com/FirebirdSQL/firebird/issues/8974 , PR #8983
        DTT:  https://github.com/FirebirdSQL/firebird/pull/9058
    Created as part of expanding LATERAL JOIN coverage, AI-request 2026-11-19.
    Checked on 6.0.0.2496-f0accd6; 6.0.0.2504-b4659fc.
"""

from decimal import Decimal

import pytest
from firebird.qa import *
from firebird.driver import DatabaseError

db = db_factory()

act = python_act('db')

SRC_DDL = """
    recreate table perm_src(id int primary key, grp int, val numeric(12,2));
    insert into perm_src(id, grp, val) values (1, 10, 100.00);
    insert into perm_src(id, grp, val) values (2, 10, 250.50);
    insert into perm_src(id, grp, val) values (3, 20, 99.99);
    insert into perm_src(id, grp, val) values (4, 20, 300.00);
    insert into perm_src(id, grp, val) values (5, 30, 42.42);
    commit;
"""

# Dataset, used both for filling all kinds of tables and for computing expected results:
DATASET = [ (1, 10, '100.00'), (2, 10, '250.50'), (3, 20, '99.99'), (4, 20, '300.00'), (5, 30, '42.42') ]

# Queries that will be run against each kind of table ('{TBL}' is replaced by table expression):
QUERIES = {
    'Q1': """
        select t.id, x.pc, cast(x.vs as varchar(30)) vs
        from {TBL} t
        cross join lateral (
            select count(*) pc, sum(d.val) vs
            from {TBL} d
            where d.grp = t.grp and d.id <> t.id
        ) x
        order by t.id
    """,
    'Q2': """
        select t.id, cast(x.mv as varchar(30)) mv
        from {TBL} t
        cross join lateral (
            select d.val mv from {TBL} d where d.grp = t.grp
            order by d.val desc
            fetch first 1 rows only
        ) x
        order by t.id
    """,
    'Q3': """
        select t.id, cast(x.mv as varchar(30)) mv
        from {TBL} t
        cross join lateral (
            select d.val mv from {TBL} d where d.grp = t.grp
            order by d.val desc
            offset 1 row fetch next 1 rows only
        ) x
        order by t.id
    """,
    # NB for Q3: 'offset 1' on single-row group produces no row => outer row is dropped.
}

def make_expected():
    exp = {}
    for qk in QUERIES:
        exp[qk] = []
    for rid, rgrp, rsval in DATASET:
        same = [ (i, Decimal(v)) for (i, g, v) in DATASET if g == rgrp ]
        peers = [ (i, v) for (i, v) in same if i != rid ]
        vals_desc = sorted([ v for (_, v) in same ], reverse = True)
        exp['Q1'].append(( str(rid), str(len(peers)), str(sum((v for (_, v) in peers), Decimal(0)).quantize(Decimal('0.01'))) if peers else None ))
        exp['Q2'].append(( str(rid), f'{vals_desc[0]:.2f}' ))
        # NB: Q3 uses 'offset 1 row fetch next 1 rows only': for group with single row
        # it returns NO row at all, so outer row id 5 is dropped by cross join lateral:
        if len(vals_desc) > 1:
            exp['Q3'].append(( str(rid), f'{vals_desc[1]:.2f}' ))
    return exp

EXPECTED = make_expected()

def fetch_as_str(cur, sql):
    cur.execute(sql)
    return [ tuple(None if v is None else str(v) for v in row) for row in cur.fetchall() ]

def run_checked(cur, tbl_expr, tag):
    for qk, qsql in QUERIES.items():
        got = fetch_as_str(cur, qsql.replace('{TBL}', tbl_expr))
        assert got == EXPECTED[qk], (
            f'{tag}: query {qk} mismatch\n'
            f'expected: {EXPECTED[qk]}\n'
            f'got:      {got}'
        )

def safe_commit(con):
    # con.commit() raises AttributeError when the main transaction has not been started yet
    try:
        con.commit()
    except AttributeError:
        pass

def try_ddl(con, sql):
    safe_commit(con)  # close implicit transaction so that DDL (alter/drop index) has no locks
    try:
        con.execute_immediate(sql)
    except DatabaseError:
        pass
    safe_commit(con)

@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action):
    act.isql(switches=['-q'], input=SRC_DDL, combine_output=True)
    assert act.return_code == 0, act.stdout
    act.reset()

    with act.db.connect() as con:
        cur = con.cursor()

        ############################################
        # A. PERMANENT table: states present / inactive / absent
        ############################################
        try_ddl(con, 'recreate table perm_k(id int, grp int, val numeric(12,2))')
        cur.execute('insert into perm_k(id, grp, val) select id, grp, val from perm_src')
        con.commit()
        try_ddl(con, 'create index perm_k_grp on perm_k(grp)')
        run_checked(cur, 'perm_k', 'permanent/index-present')

        try_ddl(con, 'alter index perm_k_grp inactive')
        run_checked(cur, 'perm_k', 'permanent/index-inactive')

        try_ddl(con, 'alter index perm_k_grp active')
        try_ddl(con, 'drop index perm_k_grp')
        run_checked(cur, 'perm_k', 'permanent/index-absent')

        ############################################
        # B. GTT ON COMMIT PRESERVE ROWS: states present / inactive / absent.
        # Connection-scoped data survives commit, single fill is enough.
        ############################################
        try_ddl(con, 'recreate global temporary table gtt_k(id int, grp int, val numeric(12,2)) on commit preserve rows')
        cur.execute('insert into gtt_k(id, grp, val) select id, grp, val from perm_src')
        con.commit()
        try_ddl(con, 'create index gtt_k_grp on gtt_k(grp)')
        run_checked(cur, 'gtt_k', 'gtt-preserve/index-present')

        try_ddl(con, 'alter index gtt_k_grp inactive')
        run_checked(cur, 'gtt_k', 'gtt-preserve/index-inactive')

        try_ddl(con, 'alter index gtt_k_grp active')
        try_ddl(con, 'drop index gtt_k_grp')
        run_checked(cur, 'gtt_k', 'gtt-preserve/index-absent')

        ############################################
        # C. GTT ON COMMIT DELETE ROWS: states present / inactive / absent.
        # Data is transaction-scoped: table must be re-filled after each commit.
        ############################################
        try_ddl(con, 'recreate global temporary table gtd_k(id int, grp int, val numeric(12,2)) on commit delete rows')
        try_ddl(con, 'create index gtd_k_grp on gtd_k(grp)')

        cur.execute('insert into gtd_k(id, grp, val) select id, grp, val from perm_src')
        run_checked(cur, 'gtd_k', 'gtt-delete/index-present')

        # transaction-scoped visibility through lateral: after commit lateral must see nothing
        con.commit()
        got = fetch_as_str(cur, QUERIES['Q1'].replace('{TBL}', 'gtd_k'))
        assert got == [], f'gtt-delete: after commit lateral still returned rows: {got}'

        try_ddl(con, 'alter index gtd_k_grp inactive')
        cur.execute('insert into gtd_k(id, grp, val) select id, grp, val from perm_src')
        run_checked(cur, 'gtd_k', 'gtt-delete/index-inactive')
        con.commit()

        try_ddl(con, 'alter index gtd_k_grp active')
        try_ddl(con, 'drop index gtd_k_grp')
        cur.execute('insert into gtd_k(id, grp, val) select id, grp, val from perm_src')
        run_checked(cur, 'gtd_k', 'gtt-delete/index-absent')
        con.commit()

        ############################################
        # D. LTT (local temporary table): states present / inactive / absent.
        # LTT definition is connection-local: it is created here, in this very connection.
        ############################################
        try_ddl(con, 'create local temporary table ltt_k(id int, grp int, val numeric(12,2)) on commit preserve rows')
        cur.execute('insert into ltt_k(id, grp, val) select id, grp, val from perm_src')
        con.commit()
        try_ddl(con, 'create index ltt_k_grp on ltt_k(grp)')
        run_checked(cur, 'ltt_k', 'ltt/index-present')

        try_ddl(con, 'alter index ltt_k_grp inactive')
        run_checked(cur, 'ltt_k', 'ltt/index-inactive')

        try_ddl(con, 'alter index ltt_k_grp active')
        try_ddl(con, 'drop index ltt_k_grp')
        run_checked(cur, 'ltt_k', 'ltt/index-absent')

        ############################################
        # E. PTT (packaged temporary tables): states present / absent.
        # Public (header) table participates in lateral queries from the outer scope,
        # private (body) table is accessible only via packaged routine (checked through
        # selectable procedure called inside lateral derived table).
        ############################################
        pkg_head_ix = """
            create package pg_lat_ix as
            begin
                temporary table ptt_pub(id int, grp int, val numeric(12,2)) on commit preserve rows unique index ptt_pub_uq(id);
                procedure ptt_fill;
                procedure p_priv_detail(a_grp int) returns (did int, val numeric(12,2));
            end
        """
        pkg_head_no_ix = """
            create package pg_lat_ix as
            begin
                temporary table ptt_pub(id int, grp int, val numeric(12,2)) on commit preserve rows;
                procedure ptt_fill;
                procedure p_priv_detail(a_grp int) returns (did int, val numeric(12,2));
            end
        """
        pkg_body = """
            recreate package body pg_lat_ix as
            begin
                temporary table ptt_priv(id int, grp int, val numeric(12,2)) on commit preserve rows;
                procedure ptt_fill as
                begin
                    delete from ptt_priv;
                    delete from ptt_pub;
                    insert into ptt_priv(id, grp, val) select id, grp, val from perm_src;
                    insert into ptt_pub (id, grp, val) select id, grp, val from perm_src;
                end
                procedure p_priv_detail(a_grp int) returns (did int, val numeric(12,2)) as
                begin
                    for
                        select p.id, p.val from ptt_priv p where p.grp = :a_grp order by p.id
                        into :did, :val
                    do
                        suspend;
                end
            end
        """
        exp_priv = []
        for rid, rgrp, _ in DATASET:
            for did, dgrp, dval in DATASET:
                if dgrp == rgrp:
                    exp_priv.append((str(rid), str(did), f'{Decimal(dval):.2f}'))

        for state, head in ( ('ptt/index-present', pkg_head_ix), ('ptt/index-absent', pkg_head_no_ix) ):
            try_ddl(con, 'drop package body pg_lat_ix')
            try_ddl(con, 'drop package pg_lat_ix')
            try_ddl(con, head)
            try_ddl(con, pkg_body)
            cur.callproc('pg_lat_ix.ptt_fill')
            con.commit()

            # public header table directly in lateral queries from the outer scope:
            run_checked(cur, 'pg_lat_ix.ptt_pub', state)

            # private body table via packaged selectable procedure called from lateral:
            got = fetch_as_str(cur, """
                select t.id, p.did, cast(p.val as varchar(30)) val
                from perm_src t
                left join lateral (select * from pg_lat_ix.p_priv_detail(t.grp) q) p on true
                order by t.id, p.did
            """)
            assert got == exp_priv, f'{state}: private PTT via packaged proc mismatch\nexpected: {exp_priv}\ngot: {got}'

        ############################################
        # F. DTT (declared local temporary tables inside PSQL): states present / absent.
        # One execute block per state: declares DTT, fills it, then runs all three
        # lateral queries in loops; Q1 emits (id, pc, vs, null, null),
        # Q2 emits (id, null, null, max_val, null), Q3 emits (id, null, null, 2nd_val, null).
        ############################################
        def dtt_query(with_index: bool):
            idx_clause = ' ascending index dtt_k_ix1(grp)' if with_index else ''
            return f"""
                execute block returns (id int, pc int, vs varchar(30), mv varchar(30), sv varchar(30)) as
                    declare local temporary table dtt_k(id int, grp int, val numeric(12,2)){idx_clause};
                begin
                    insert into dtt_k(id, grp, val) select id, grp, val from perm_src;

                    for
                        select t.id, x.pc, cast(x.vs as varchar(30)), null, null
                        from dtt_k t
                        cross join lateral (
                            select count(*) pc, sum(d.val) vs
                            from dtt_k d
                            where d.grp = t.grp and d.id <> t.id
                        ) x
                        order by t.id
                        into :id, :pc, :vs, :mv, :sv
                    do
                        suspend;

                    for
                        select t.id, null, null, cast(x.mv as varchar(30)), null
                        from dtt_k t
                        cross join lateral (
                            select d.val mv from dtt_k d where d.grp = t.grp
                            order by d.val desc
                            fetch first 1 rows only
                        ) x
                        order by t.id
                        into :id, :pc, :vs, :mv, :sv
                    do
                        suspend;

                    for
                        select t.id, null, null, cast(x.mv as varchar(30)), null
                        from dtt_k t
                        cross join lateral (
                            select d.val mv from dtt_k d where d.grp = t.grp
                            order by d.val desc
                            offset 1 row fetch next 1 rows only
                        ) x
                        order by t.id
                        into :id, :pc, :vs, :mv, :sv
                    do
                        suspend;
                end
            """

        exp_rows = []
        for rid, pc, vs in EXPECTED['Q1']:
            exp_rows.append((rid, pc, vs, None, None))
        for rid, mv in EXPECTED['Q2']:
            exp_rows.append((rid, None, None, mv, None))
        for rid, sv in EXPECTED['Q3']:
            exp_rows.append((rid, None, None, sv, None))

        for with_index in (True, False):
            cur.execute(dtt_query(with_index))
            got = [ tuple(None if v is None else str(v) for v in row) for row in cur.fetchall() ]
            assert got == exp_rows, (
                f'dtt/index-{"present" if with_index else "absent"} mismatch\n'
                f'expected: {exp_rows}\n'
                f'got:      {got}'
            )
