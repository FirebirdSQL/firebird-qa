def make_quad(high: int, low: int) -> fbapi.ISC_QUAD:
    q = fbapi.ISC_QUAD()
    q.high = high
    q.low = low
    return q


def create_blob_with_data(att, tra, data: bytes) -> fbapi.ISC_QUAD:
    """Create temp blob with given content, return its id."""
    quad = make_quad(0, 0)
    blb = att.create_blob(tra, quad)
    blb.put_segment(len(data), data)
    blb.close()
    return quad


def insert_blob_row(att, tra, sql: str, int_val: int, quad: fbapi.ISC_QUAD) -> None:
    """Low-level INSERT of (int, blob_id): used to store the blob id into the table."""
    stmt = att.prepare(tra, sql, 3)
    meta = stmt.get_input_metadata()
    buf = bytearray(meta.get_message_length())
    struct.pack_into('h', buf, meta.get_null_offset(0), 0)   # id: not null
    struct.pack_into('i', buf, meta.get_offset(0), int_val)
    struct.pack_into('h', buf, meta.get_null_offset(1), 0)   # blob: not null
    struct.pack_into('<II', buf, meta.get_offset(1), quad.high & 0xFFFFFFFF, quad.low)
    stmt.execute(tra, meta, bytes(buf), None, None)
    stmt.free()


def get_permanent_blob_id(con, sql_select: str) -> tuple:
    """Low-level SELECT of a single blob column; returns the PERMANENT blob id
    (relation_id, blob_number), taken from the raw fetch message buffer.
    The engine puts the blob id into the output message before the driver
    materializes its content, so this is the only reliable way to get it."""
    att = con._att
    tra = con.main_transaction._tra
    stmt = att.prepare(tra, sql_select, 3)
    out_meta = stmt.get_output_metadata()
    rs = stmt.open_cursor(tra, None, None, out_meta, CursorFlag.NONE)
    buf = create_string_buffer(out_meta.get_message_length())
    state = rs.fetch_next(buf)
    assert state == StateResult.OK, 'no row fetched, check scenario'
    high, low = struct.unpack_from('<II', buf, out_meta.get_offset(0))
    rs.close()
    stmt.free()
    assert high != 0, 'blob id remained TEMP (high word must hold relation id)'
    return (high, low)


def batch_register_and_insert(att, tra, ref_blob_id: tuple, placeholder_low: int, row_id: int):
    """Create batch for 'insert into ATTACKER_T ...' with BLOB_ID_USER policy,
    register ref_blob_id as the blob that placeholder_low must substitute with,
    add one message and execute the batch.
    Returns (stored_ok, DatabaseError_or_None)."""
    from firebird.driver import core as _dcore
    pb = _dcore._util.get_xpb_builder(XpbKind.BATCH, None)
    pb.clear()
    pb.insert_int(TAG_BLOB_POLICY, BLOB_ID_USER)
    params = pb.get_buffer()

    batch = att.create_batch(tra, 'insert into ATTACKER_T (id, payload) values (?, ?)', 3,
                             None, params)
    try:
        meta = batch.get_metadata()
        ph = make_quad(0, placeholder_low)  # attacker-chosen placeholder id
        batch.register_blob(make_quad(*ref_blob_id), ph)
        buf = bytearray(meta.get_message_length())
        struct.pack_into('h', buf, meta.get_null_offset(0), 0)
        struct.pack_into('i', buf, meta.get_offset(0), row_id)
        struct.pack_into('h', buf, meta.get_null_offset(1), 0)
        struct.pack_into('<II', buf, meta.get_offset(1), 0, placeholder_low)
        batch.add(1, bytes(buf))
        try:
            batch.execute(tra)
            return True, None
        except DatabaseError as e:
            return False, e
    finally:
        batch.release()


def read_attacker_payload(con, row_id: int) -> bytes:
    """Read back payload blob content from ATTACKER_T (as attacker)."""
    cur = con.cursor()
    cur.execute('select payload from ATTACKER_T where id = ?', (row_id,))
    row = cur.fetchone()[0]
    con.commit()
    return row if isinstance(row, bytes) else bytes(row.read())


