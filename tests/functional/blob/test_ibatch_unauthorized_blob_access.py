        insert_blob_row(att, tra, 'insert into VICTIM_T (id, secret_data) values (?, ?)', 1, secret_blob)
        victim_id = get_permanent_blob_id(con, 'select secret_data from VICTIM_T where id = 1')

        open_blob = create_blob_with_data(att, tra, OPEN_DATA)
        insert_blob_row(att, tra, 'insert into OPEN_T (id, payload) values (?, ?)', 1, open_blob)
        open_id = get_permanent_blob_id(con, 'select payload from OPEN_T where id = 1')

