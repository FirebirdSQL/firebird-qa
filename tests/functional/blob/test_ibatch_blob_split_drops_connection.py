@pytest.mark.version('>=4.0.8')
def test_1(act: Action, capsys):

    # Will be shown only if test fails, see below capsys.readouterr().out:
    # --------------------------------
    print(f"Server   : {act.vars['server']} v{act.vars['version']} "
          f"[{act.vars['server-arch']}, {act.vars['arch']}]")
    print(f"Client   : {act.vars['fbclient']}")
    print(f"DSN      : {act.db.dsn}")
    # --------------------------------

    phases = {p.tag: p for p in _PHASES}
    outcomes = {}
    details = {}

    # Control phases: single connection, MUST pass on all builds (pre-fix too).
    with act.db.connect() as con:
        for tag in ("C1", "C2", "C3"):
            outcomes[tag], details[tag] = _run_phase(con, phases[tag])

    # MAIN phase: on pre-fix builds this drops the connection.
    with act.db.connect() as con_main:
        outcomes["MAIN"], details["MAIN"] = _run_phase(con_main, phases["MAIN"])

    for tag in ("C1", "C2", "C3", "MAIN"):
        print(f"--- phase {tag:4s} ({phases[tag].blob_count} x {phases[tag].blob_size} B "
              f"{phases[tag].blob_kind} BLOB): {outcomes[tag]}: {details[tag]}")

    if any(outcomes[t] != "ok" for t in ("C1", "C2", "C3")):
        act.stdout = "CHECK NOT PASSED (control phase failed):\n\n" + capsys.readouterr().out
    elif outcomes["MAIN"] == "ok":
        act.stdout = EXPECTED_MSG
    elif outcomes["MAIN"] == "net_error":
        act.stdout = ("Bug #9251 raised: connection dropped while sending a batch whose "
                      "stream BLOB continues into the next packet "
                      "(fix 2f04ebd/8512da6/56f03d5 not present):\n\n" + capsys.readouterr().out)
    else:
        act.stdout = "CHECK NOT PASSED (non-network failure in MAIN phase):\n\n" + capsys.readouterr().out

    assert act.clean_stdout == EXPECTED_MSG
