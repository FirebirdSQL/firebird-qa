# ------------------------------ constants ---------------------------------

BLOB_SIZE = 1025*1024 # must be [much] larger than ClientBatchBuffer (128 KB) -> buffer splits mid-BLOB
CHUNK_SIZE = 16384    # the pattern used in the issue report
MAIN_BLOB_COUNT = 3
SMALL_BLOB_SIZE = 1000
SMALL_BLOB_COUNT = 20

# --- BPB building blocks (src/include/firebird/impl/consts_pub.h) ---
# BPB is a "Tagged" (traditional DPB-style) clumplet buffer:
#   version byte, then tag + 1-byte length + value entries.
BPB_VERSION1 = 0x01
BPB_TYPE = 0x03
BPB_TYPE_SEGMENTED = 0x00
BPB_TYPE_STREAM = 0x01
SEG_BPB = bytes([BPB_VERSION1, BPB_TYPE, 0x01, BPB_TYPE_SEGMENTED])
STR_BPB = bytes([BPB_VERSION1, BPB_TYPE, 0x01, BPB_TYPE_STREAM])
NO_BPB = b""

# --- createBatch() params: buffer starts with IBatch::VERSION1 byte, then
# WideTagged clumplets: tag(1) + length(4 LITTLE-endian) + data (vax/big-endian int)
BATCH_VERSION1 = 0x01
TAG_BLOB_POLICY = 0x04
BLOB_ID_USER = 0x02
BATCH_PARAMS = bytes([BATCH_VERSION1, TAG_BLOB_POLICY, 0x01, 0x00, 0x00, 0x00, BLOB_ID_USER])

NET_ERR_MARKS = (
    "Error writing data to the connection",
    "Error reading data from the connection",
    "Unable to complete network request",
    "Error occurred while performing",
)


class _Phase:
    def __init__(self, tag, blob_count, blob_size, blob_kind, default_bpb, content):
        self.tag = tag
        self.table = f"GH9251_{tag}"
        self.blob_count = blob_count
        self.blob_size = blob_size
        self.blob_kind = blob_kind          # 'stream' - explicit stream BPB, 'segmented' - no BPB
        self.default_bpb = default_bpb      # None - do not call set_default_bpb
        self.content = content              # bytes for every BLOB of the phase


def _det_pattern(size):
    """Deterministic pseudo-binary content for control BLOBs."""
    return bytes((i * 131 + 17) % 256 for i in range(size))


_PHASES = [
    _Phase("C1", SMALL_BLOB_COUNT, SMALL_BLOB_SIZE, "stream", SEG_BPB, _det_pattern(SMALL_BLOB_SIZE)),
    _Phase("C2", 1, BLOB_SIZE, "segmented", SEG_BPB, _det_pattern(BLOB_SIZE)),
    _Phase("C3", 1, BLOB_SIZE, "stream", STR_BPB, _det_pattern(BLOB_SIZE)),
    _Phase("MAIN", MAIN_BLOB_COUNT, BLOB_SIZE, "stream", SEG_BPB, b"\xff" * BLOB_SIZE),
]

# ------------------------------- helpers ----------------------------------

def _is_network_error(exc):
    text = str(exc)
    if any(mark in text for mark in NET_ERR_MARKS):
        return True
    codes = tuple(getattr(exc, "gds_codes", ()) or ())
    isc_net_read_err = 335544725
    isc_net_write_err = 335544726
    return any(code in (isc_net_read_err, isc_net_write_err) for code in codes)


def _run_phase(con, phase):
    """Add all blobs of the given phase to a batch and execute it.

    Returns (outcome, details). outcome: 'ok' | 'net_error' | 'error'.
    """
    try:
        cur = con.cursor()
        cur.execute(f"DELETE FROM {phase.table}")
        con.commit()

        con.begin()
        itx = con.main_transaction._tra
        istmt = con._att.prepare(itx, f"INSERT INTO {phase.table} (ID, B) VALUES (?, ?)",
                                 con.sql_dialect)
        imeta = istmt.get_input_metadata()
        ibatch = istmt.create_batch(imeta, BATCH_PARAMS)

        if phase.default_bpb is not None:
            ibatch.set_default_bpb(phase.default_bpb)

        msg_len = imeta.get_message_length()
        off_id = imeta.get_offset(0)
        id_len = imeta.get_length(0)
        off_blob = imeta.get_offset(1)
        blob_bpb = STR_BPB if phase.blob_kind == "stream" else NO_BPB

        for seq in range(1, phase.blob_count + 1):
            # message: {ID = seq, B = blob-id seq}
            msg = bytearray(msg_len)  # zeros -> all NULL-indicators = 0
            msg[off_id:off_id + id_len] = seq.to_bytes(id_len, "little")
            msg[off_blob:off_blob + 8] = struct.pack("<iI", 0, seq)  # ISC_QUAD: high=0, low=seq
            ibatch.add(1, bytes(msg))

            # blob with own BPB (stream) or without one (default BPB applies)
            ibatch.add_blob(0, b"", fbapi.ISC_QUAD(0, seq), blob_bpb)

            data = phase.content
            for ofs in range(0, len(data), CHUNK_SIZE):
                chunk = data[ofs:ofs + CHUNK_SIZE]
                ibatch.append_blob_data(len(chunk), chunk)

        ibatch.execute(itx)
        con.commit()
        # NOTE: do not call ibatch.close() - it releases the IBatch interface and
        # the driver wrapper releases it once more on garbage collection.

        # verify: row count, byte length and byte-exact BLOB content
        cur = con.cursor()
        cur.execute(
            f"SELECT COUNT(*), MIN(OCTET_LENGTH(B)), MAX(OCTET_LENGTH(B)) FROM {phase.table}"
        )
        row_count, min_len, max_len = cur.fetchone()
        if row_count != phase.blob_count or min_len != phase.blob_size or max_len != phase.blob_size:
            return "error", (
                f"wrong batch result: rows={row_count} (expected {phase.blob_count}), "
                f"blob len {min_len}..{max_len} (expected {phase.blob_size}..{phase.blob_size})"
            )
        cur = con.cursor()
        cur.stream_blobs = ["B"]  # always return BLOB as stream reader, regardless of its size
        cur.execute(f"SELECT ID, B FROM {phase.table} ORDER BY ID")
        bad = [row_id for row_id, blob in cur.fetchall() if blob.read() != phase.content]
        if bad:
            return "error", f"BLOB has wrong content for ID(s): {bad}"
        return "ok", f"{phase.blob_count} row(s) inserted, content verified"
    except Exception as exc:  # noqa: BLE001 - classified below
        if _is_network_error(exc):
            return "net_error", f"{type(exc).__name__}: {exc}"
        return "error", f"{type(exc).__name__}: {exc}"


