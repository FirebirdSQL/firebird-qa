import pytest
from firebird.qa import *
from firebird.driver import DatabaseError

MAX_SEGMENTS = 16
ISC_NO_META_UPDATE = 335544351

# Index root page layout constants per ODS major version, see NOTES.
ROOT_PAGE_LAYOUT = {
    13: dict(header = 20, slot = 12, irtd = 8),   # FB 5.x (ODS 13.x)
    14: dict(header = 24, slot = 24, irtd = 12),  # FB 6.x (ODS 14.x)
}

PAGE_SIZES = (4096, 8192, 16384, 32768)


def get_max_indices(ods_major: int, page_size: int, segments: int) -> int:
    """Max number of indices that fit on the index root page, per formula in NOTES."""
    layout = ROOT_PAGE_LAYOUT[ods_major]
    return (page_size - layout['header']) // (layout['slot'] + segments * layout['irtd'])


def check_table(con, tname, ddl, psql_tmpl, segments, ods_major, page_size) -> int:
    """Create indices on the given table in autonomous transactions until first failure
    and verify the limit against the formula. Returns expected maximum.
    """
    expected_max = get_max_indices(ods_major, page_size, segments)
    cur = con.cursor()

    cur.execute(ddl)
    # NB: commit is REQUIRED here: indices are created by ES in autonomous transaction,
    # which must be able to see the just created table.
    con.commit()

    eb = f"""
        execute block returns(failed_at int, err_gds int) as
            declare n int = 100000;
            declare i int = 0;
            declare s varchar(255);
        begin
            while (i < n) do
            begin
                s = {psql_tmpl};
                execute statement s with autonomous transaction;
                i = i + 1;
                when any do
                begin
                    failed_at = i;
                    err_gds = gdscode;
                    suspend;
                    leave;
                end
            end
            if (failed_at is null) then
            begin
                failed_at = -1;
                err_gds = -1;
                suspend;
            end
        end
    """
    cur.execute(eb)
    failed_at, err_gds = cur.fetchone()

    assert failed_at == expected_max, \
        f"Table {tname}: first failure occurred at index #{failed_at}, but formula predicts " \
        f"that exactly {expected_max} indices must fit (ODS {ods_major}, page size {page_size}, " \
        f"{segments} segment(s))"

    assert err_gds == ISC_NO_META_UPDATE, \
        f"Table {tname}: got gdscode {err_gds}, expected {ISC_NO_META_UPDATE} " \
        f"(isc_no_meta_update) (ODS {ods_major}, page size {page_size})"

    con.commit()

    cur.execute(f"select count(*) from rdb$indices where rdb$relation_name = '{tname}'")
    actual_count = cur.fetchone()[0]
    assert actual_count == expected_max, \
        f"Table {tname}: rdb$indices contains {actual_count} rows, expected {expected_max} " \
        f"(ODS {ods_major}, page size {page_size})"

    return expected_max


