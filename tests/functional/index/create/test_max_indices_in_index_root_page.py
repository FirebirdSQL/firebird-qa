@pytest.mark.ai
@pytest.mark.version('>=5.0')
def test_1(act: Action):

    cols_ddl = ', '.join(f'c{i:02d} smallint' for i in range(MAX_SEGMENTS))
    cols_idx = ', '.join(f'c{i:02d}' for i in range(MAX_SEGMENTS))

    cases = [
        dict(tname = 'T_01',
             ddl = 'create table T_01 (x smallint)',
             psql_tmpl = "'create index ix01_' || lpad(i, 5, '0') || ' on T_01 computed by (x + ' || i || ')'",
             segments = 1),
        dict(tname = 'T_16',
             ddl = f'create table T_16 ({cols_ddl})',
             psql_tmpl = f"'create index ix16_' || lpad(i, 5, '0') || ' on T_16 ({cols_idx})'",
             segments = MAX_SEGMENTS),
    ]

    # ODS version defines which layout constants must be used by the formula.
    # NB: initial DB is created by the fixture with server default page size, its page
    # size does not matter here.
    with act.db.connect() as con:
        ods_major = con.info.ods_version
        ods_minor = con.info.ods_minor_version

    if ods_major not in ROOT_PAGE_LAYOUT:
        pytest.skip(f"No formula constants for ODS {ods_major}")

    problems = []

    for page_size in PAGE_SIZES:
        if page_size == 4096 and ods_major >= 14:
            print(f"page_size {page_size}: SKIPPED, FB 6.x (ODS >= 14) does not support it "
                  f"(silently promotes page_size 4096 to 8192)")
            continue

        try:
            act.db.drop()
            act.db.create(page_size = page_size)
            # NB: same as db_factory fixture does at its setup. Without this, DB is created
            # with forced writes ON and every autonomous DDL commit waits for disk sync,
            # which makes the whole test several times slower.
            act.db.set_async_write()

            max_indices = {}
            with act.db.connect() as con:
                assert con.info.page_size == page_size, \
                    f"Requested page size {page_size} but DB was created with {con.info.page_size}"

                for case in cases:
                    max_indices[case['tname']] = check_table(
                        con, case['tname'], case['ddl'], case['psql_tmpl'],
                        case['segments'], ods_major, page_size)

                # index root page is per-relation: filling T_16 must not affect T_01, and vice versa
                for case in cases:
                    cur = con.cursor()
                    cur.execute(f"select count(*) from rdb$indices "
                                f"where rdb$relation_name = '{case['tname']}'")
                    final_count = cur.fetchone()[0]
                    assert final_count == max_indices[case['tname']], \
                        f"Table {case['tname']}: final count of indices ({final_count}) differs " \
                        f"from {max_indices[case['tname']]} (ODS {ods_major}, page size {page_size})"

            print(f"ODS {ods_major}.{ods_minor}, page {page_size}: "
                  f"T_01 = {max_indices['T_01']}, T_16 = {max_indices['T_16']} indices created, "
                  f"as predicted by formula")

        except (AssertionError, DatabaseError) as e:
            problems.append(f"page_size = {page_size}: {type(e).__name__}: {e}")

    if problems:
        pytest.fail("Index root page capacity check FAILED:\n" + "\n".join(problems))
