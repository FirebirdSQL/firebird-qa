import subprocess
from pathlib import Path

import pytest
from firebird.qa import *

try:
    # leaf folder is a package inside the main firebird-qa tree (has __init__.py)
    from . import fp_helpers as fp
except ImportError:
    # loose folder without __init__.py, e.g. qa\zcode\probe01
    import fp_helpers as fp

db = db_factory(charset='UTF8')
act = python_act('db')

db_res = db_factory(filename='fp05_restored.fdb', charset='UTF8')
act_res = python_act('db_res')

tmp_fbk = temp_file('fp05_backup.fbk')
tmp_monly_fbk = temp_file('fp05_monly.fbk')

SCOPE_DDL = """
    create table t_pers (id integer primary key, val varchar(30));
    insert into t_pers values (1, 'persistent-one');
    insert into t_pers values (2, 'persistent-two');
    create view v_pers (id, val) as select id, val from t_pers;
    create global temporary table g_tmp (id integer) on commit preserve rows;
    commit;
"""

PERS_QUERY = "select id, val from t_pers order by id"


def prepare_scope_db(act: Action) -> None:
    act.isql(switches=['-q'], input=SCOPE_DDL, combine_output=True)
    assert act.stdout == '', act.stdout
    act.reset()


def meta_without_create(act: Action) -> str:
    meta = act.extract_meta(charset='utf8', io_enc='utf8')
    act.reset()
    return '\n'.join(x for x in meta.splitlines() if 'CREATE DATABASE' not in x)


@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, act_res: Action, tmp_fbk: Path, tmp_monly_fbk: Path):
    prepare_scope_db(act)
    src_rows = fp.fetch_rows(act, PERS_QUERY)
    src_meta = meta_without_create(act)

    # --- part 1: eligibility scope (persistent data transfers, view/gtt kept) ---
    fp.gbak_backup(act, Path(act.db.db_path), tmp_fbk, fast=True)
    fp.gbak_restore(act, tmp_fbk, Path(act_res.db.db_path), fast=True)

    assert fp.fetch_rows_from(act_res, PERS_QUERY) == src_rows

    # view works and GTT definition exists (its data is not backed up)
    assert fp.fetch_rows_from(act_res, "select id, val from v_pers order by id") == src_rows
    assert fp.fetch_rows_from(
        act_res,
        "select count(*) from rdb$relations where rdb$relation_name = 'G_TMP'"
    ) == [(1,)]

    assert meta_without_create(act_res) == src_meta

    # --- part 2: metadata-only backup/restore via fast path ---
    fp.gbak_backup(act, Path(act.db.db_path), tmp_monly_fbk, fast=True, extra=['-m'])
    fp.gbak_restore(act, tmp_monly_fbk, Path(act_res.db.db_path), fast=True)

    with act_res.db.connect() as con:
        cur = con.cursor()
        cur.execute("select count(*) from t_pers")
        assert cur.fetchone()[0] == 0, "metadata-only restore brought rows"

    # --- part 3: fbsvcmgr Services API bits ---
    if Path(tmp_fbk).exists():
        Path(tmp_fbk).unlink()

    fbsvcmgr = Path(act.bin_dir) / 'fbsvcmgr.exe'
    creds = ['-user', act.db.user, '-password', act.db.password]
    svc = fp.svc_mngr(act)
    w = str(fp.PARALLEL_WORKERS)

    p = subprocess.run(
        [str(fbsvcmgr), svc] + creds +
        ['action_backup', 'dbname', str(act.db.db_path),
         'bkp_file', str(tmp_fbk), 'bkp_parallel_workers', w, 'bkp_fast_path'],
        capture_output=True, text=True, errors='replace')
    assert p.returncode == 0, f"fbsvcmgr backup failed: {p.stdout} {p.stderr}"

    p = subprocess.run(
        [str(fbsvcmgr), svc] + creds +
        ['action_restore', 'bkp_file', str(tmp_fbk),
         'dbname', str(act_res.db.db_path), 'res_parallel_workers', w,
         'res_replace', 'res_fast_path'],
        capture_output=True, text=True, errors='replace')
    assert p.returncode == 0, f"fbsvcmgr restore failed: {p.stdout} {p.stderr}"

    assert fp.fetch_rows_from(act_res, PERS_QUERY) == src_rows
