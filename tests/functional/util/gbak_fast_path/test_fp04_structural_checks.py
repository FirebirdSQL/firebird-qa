from pathlib import Path

import pytest
from firebird.qa import *

try:
    # leaf folder is a package inside the main firebird-qa tree (has __init__.py)
    from . import fp_helpers as fp
except ImportError:
    # loose folder without __init__.py, e.g. qa\zcode\probe01
    import fp_helpers as fp

db = db_factory(charset='UTF8')
act = python_act('db')

tmp_fbk = temp_file('fp04_backup.fbk')
tmp_corrupt = temp_file('fp04_corrupt.fbk')
tmp_target = temp_file('fp04_target.fdb')

DDL = """
    create table t_struct (id integer primary key, val varchar(50));
    insert into t_struct values (1, 'one');
    insert into t_struct values (2, 'two');
    commit;
"""


@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, tmp_fbk: Path, tmp_corrupt: Path, tmp_target: Path):
    act.isql(switches=['-q'], input=DDL, combine_output=True)
    assert act.stdout == '', act.stdout
    act.reset()

    # 1. no '-se' switch: FAST_PATH must be refused before doing any work
    act.gbak(switches=['-b', '-fast_path', act.db.dsn, str(tmp_fbk)],
             combine_output=True)
    assert act.return_code != 0, "FAST_PATH was accepted without -service"
    assert 'requires the -service option' in act.stdout, act.stdout
    act.reset()

    # 2. act.db.dsn is a remote name, e.g. 'localhost/3600:C:\\...\\test.fdb':
    #    FAST_PATH selects the engine provider directly, so remote prefixes must fail
    sw = ["-se", fp.svc_mngr(act), "-b", "-parallel", str(fp.PARALLEL_WORKERS),
          "-fast_path", act.db.dsn, str(tmp_fbk)]
    act.gbak(switches=sw, combine_output=True)
    assert act.return_code != 0, "FAST_PATH accepted a remote-prefixed database name"
    assert 'ERROR' in act.stdout.upper(), act.stdout
    act.reset()

    # 3. a healthy fast backup, then structural damage spread over the stream:
    #    both restore paths must detect it and abort (fail-fast, no row skipping)
    fp.gbak_backup(act, Path(act.db.db_path), tmp_fbk, fast=True)

    # flip bytes at several fixed fractions of the stream length. A single flip
    # is NOT used: whether it breaks the restore depends on where it lands,
    # which varies with file size/paths (one benign byte -> restore succeeds).
    # Damage spread over the stream reliably hits names, length or XDR tag
    # bytes, so BOTH restore modes must abort (fail-fast, no row skipping).
    data = bytearray(Path(tmp_fbk).read_bytes())
    for frac in range(1, 10):
        data[len(data) * frac // 10] ^= 0xFF
    Path(tmp_corrupt).write_bytes(bytes(data))

    for restore_fast in (False, True):
        if Path(tmp_target).exists():
            # a previously aborted restore may leave a partial database behind
            Path(tmp_target).unlink()

        tag = f"restore={'FAST' if restore_fast else 'NORM'}"
        rc, out = fp.gbak_restore(act, tmp_corrupt, Path(tmp_target), fast=restore_fast,
                                  replace=False, expect_fail=True)
        assert rc != 0, f"{tag}: corrupted backup was restored without error"
        assert 'ERROR' in out.upper(), out
