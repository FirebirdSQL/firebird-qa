from pathlib import Path

import pytest
from firebird.qa import *

try:
    # leaf folder is a package inside the main firebird-qa tree (has __init__.py)
    from . import fp_helpers as fp
except ImportError:
    # loose folder without __init__.py, e.g. qa\zcode\probe01
    import fp_helpers as fp

db = db_factory(charset='UTF8')
act = python_act('db')

db_res = db_factory(filename='fp02_restored.fdb', charset='UTF8')
act_res = python_act('db_res')

tmp_fbk = temp_file('fp02_backup.fbk')

UNICODE_QUERY = "select id, c_text from t_unicode order by id"
BLOB_QUERY = "select id, c_bin from t_bins order by id"


@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, act_res: Action, tmp_fbk: Path):
    with act.db.connect() as con:
        cur = con.cursor()
        cur.execute("create table t_unicode (id integer primary key, c_text varchar(200))")
        cur.execute("create table t_bins (id integer primary key, c_bin blob sub_type 0)")
        # european and cyrillic lines are natural messages of ~200 characters
        samples = [
            'Plain ASCII message: the quick brown fox jumps over the lazy dog while '
            'packing five boxes of mixed vintage jams and quartz jugs for the long trip '
            'north of the old harbor town.'

            # cyrillic (russian, belarusian, ukrainian letters):
            ,'Кириллица: ЁёЙй ўЎ — кириллическое письмо используется в России, Украине, '
            'Беларуси, Сербии и Болгарии, а буквы Ё, Ї, Ў хорошо показывают различия '
            'национальных алфавитов.'

            # japanese (kanji + katakana):
            ,'中文漢字テスト'

            # french (diacritics, cedilla, oe ligature):
            ,'Résumé français : côté, œuvre, ça va — leçon où les accents aigus, graves '
            'et circonflexes se mêlent à la cédille, à la ligature œ et aux voyelles '
            "naïves de l'été passé."

            # finnish (a-umlaut, o-umlaut, ring-a):
            ,'Suomi: väylä, häälyttää, ångest — suomen kielessä ä:n ja ö:n käyttö on '
            'täysin arkipäivää, ja pitkä sana lentokonesuihkuturbiinimoottori'
            'apumekaanikkoaliupseeri osoittaa, miten sanoja yhdistellään.'

            # icelandic (thorn, eth, ae, o-acute):
            ,'Íslenska: Þór, æði, öxi — íslenskan hefur varðveitt stafi á borð við þ, '
            'ð og æ, og marga bókstafi sem breyttust í öðrum norrænum málum fyrir '
            'alda skeið.'

            # greek:
            ,'Ελληνικά: Γειά σου κόσμε — το ελληνικό αλφάβητο χρησιμοποιείται εδώ και '
            'τρεις χιλιάδες χρόνια, και γράμματα όπως α, β, γ και δ χρησιμοποιούνται '
            'στα μαθηματικά.'

            # hindi (devanagari):
            ,'नमस्ते दुनिया'

            # farsi (persian):
            ,'فارسی: سلام دنیا'

            # arabic:
            ,'العربية: مرحبا بالعالم'

            # chinese (simplified):
            ,'简体中文：你好，世界'

            # emoji:
            ,'emoji \U0001F600\U0001F680 tail'

            # combining marks:
            ,'combining a\u0301e\u0302o\u0303'

            # quotes and backslashes:
            ,"quote' and \"double\" and \\backslash\\"

            # single character, maximal length:
            ,'x' * 200
        ]
        # georgian, thai, lao and korean (hangul) cost three utf-8 bytes per
        # character; varchar(200) counts characters rather than bytes, so these
        # lines are natural messages padded with trailing spaces to exactly the
        # declared maximum of 200 characters - the widest possible rows for them
        samples += [
            'ქართული ანბანი მსოფლიოს ერთ-ერთი უძველესი და უნიკალური დამწერლობაა, '
            'ხოლო ქართული ენა გამოირჩევა მდიდარი ლექსიკითა და განსაკუთრებული '
            'ფონეტიკური სისტემით.'.ljust(200)

            # thai:
            ,'ภาษาไทยเป็นภาษาที่มีเสียงวรรณยุกต์ การเขียนภาษาไทยไม่มีการเว้นวรรค'
            'ระหว่างคำ แต่จะเว้นวรรคระหว่างประโยค ซึ่งแตกต่างจากภาษาในยุโรป'
            'ส่วนใหญ่อย่างชัดเจน'.ljust(200)

            # lao:
            ,'ພາສາລາວເປັນພາສາທີ່ມີວັນນະຍຸດ ແລະ ລະບົບການຂຽນຄ້າຍຄືພາສາໄທ ຕົວອັກສອນ'
            'ລາວມີຮູບຮ່າງໂຄ້ງມົນ ແລະ ໃຊ້ເປັນທາງການໃນ ສປປ ລາວ'.ljust(200)

            # korean (hangul):
            ,'한글은 세종대왕이 창제한 한국의 고유 문자로, 자음과 모음을 조합하여 음절을 '
            '표기합니다. 과학적이고 배우기 쉬운 문자 체계로 널리 알려져 있으며 그 우수성은 '
            '널리 인정받고 있습니다.'.ljust(200)
        ]
        for i, s in enumerate(samples, start=1):
            cur.execute("insert into t_unicode values (?, ?)", (i, s))
        all_bytes = bytes(range(256))
        bin_samples = [b'', all_bytes, all_bytes * 40, b'\x00\x01\x02\xff' * 1000]
        for i, b in enumerate(bin_samples, start=1):
            cur.execute("insert into t_bins values (?, ?)", (i, b))
        con.commit()

    src_text = fp.fetch_rows(act, UNICODE_QUERY)
    src_bins = fp.fetch_rows(act, BLOB_QUERY)
    assert len(src_text) == len(samples) and len(src_bins) == len(bin_samples)

    fp.gbak_backup(act, Path(act.db.db_path), tmp_fbk, fast=True)
    fp.gbak_restore(act, tmp_fbk, Path(act_res.db.db_path), fast=True)

    assert fp.fetch_rows_from(act_res, UNICODE_QUERY) == src_text, "unicode content differs"
    assert fp.fetch_rows_from(act_res, BLOB_QUERY) == src_bins, "binary blob content differs"
