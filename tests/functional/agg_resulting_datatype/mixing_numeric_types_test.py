@pytest.mark.version('>=4.0')
@pytest.mark.ai
def test_union_mixing_numeric_types(act: Action):

    sql_parts = ['set bail off;', 'set sqlda_display on;', 'set echo off;', '']
    expected_parts = []
    for mx, t1, t2, t3 in COMBOS:
        lits = (MIN_MAP[t1], MAX_MAP[t2], MIN_MAP[t3])  # pos1 -> min, pos2 -> max, pos3 -> min
        dts = (CAST_MAP[t1], CAST_MAP[t2], CAST_MAP[t3])
        for quant in ('union all', 'union distinct'):
            sql_parts.extend([
                'select cast(%s as %s) from rdb$database' % (lits[0], dts[0]),
                quant,
                'select cast(%s as %s) from rdb$database' % (lits[1], dts[1]),
                quant,
                'select cast(%s as %s) from rdb$database rows 0;' % (lits[2], dts[2]),
                '',
            ])
            expected_parts.append(merged_line(t1, t2, t3))

    act.script = '\n'.join(sql_parts)
    act.expected_stdout = '\n'.join(expected_parts)
    act.execute(combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
