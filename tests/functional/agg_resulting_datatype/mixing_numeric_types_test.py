# --------------------------- merge model ----------------------------------------------

RANK = {'short': 1, 'long': 2, 'int64': 3, 'int128': 4}
SQLUDA = {
    'short': '500 SHORT', 'long': '496 LONG', 'int64': '580 INT64', 'int128': '32752 INT128',
    'float': '482 FLOAT', 'double': '480 DOUBLE',
    ('decf', 16): '32760 DECFLOAT(16)', ('decf', 34): '32762 DECFLOAT(34)',
}
LEN = {'short': 2, 'long': 4, 'int64': 8, 'int128': 16,
       'float': 4, 'double': 8, ('decf', 16): 8, ('decf', 34): 16}

def one_type(dt):
    """internal model of the type: (storage, scale, subtype)"""
    if dt == 'smallint':           return ('short', 0, 0)
    if dt == 'int':                return ('long', 0, 0)
    if dt == 'bigint':             return ('int64', 0, 0)
    if dt == 'int128':             return ('int128', 0, 0)
    if dt in ('numeric(4)', 'numeric(4,4)'):     return ('short', -4 if ',' in dt else 0, 1)
    if dt in ('decimal(4)', 'decimal(4,4)'):     return ('long', -4 if ',' in dt else 0, 2)
    if dt in ('numeric(18)', 'numeric(18,18)'):  return ('int64', -18 if ',' in dt else 0, 1)
    if dt in ('numeric(38)', 'numeric(38,38)'):  return ('int128', -38 if ',' in dt else 0, 1)
    if dt == 'float':              return ('float', 0, 0)
    if dt == 'double precision':   return ('double', 0, 0)
    if dt == 'decfloat(16)':       return (('decf', 16), 0, 0)
    if dt == 'decfloat(34)':       return (('decf', 34), 0, 0)
    raise KeyError(dt)

def merge2(a, b):
    if a[0][0] == 'decf' or b[0][0] == 'decf':
        if a[0][0] == 'decf' and b[0][0] == 'decf':
            return (('decf', max(a[0][1], b[0][1])), 0, 0)
        return a if a[0][0] == 'decf' else b
    if a[0] in ('float', 'double') or b[0] in ('float', 'double'):
        if a[0] == 'double' or b[0] == 'double':
            return ('double', 0, 0)
        return ('float', 0, 0)
    base = max(a[0], b[0], key=lambda x: RANK[x])
    scale = min(a[1], b[1])   # scales are <= 0: max precision after point = min value
    sub = max(a[2], b[2])     # decimal(2) > numeric(1) > no sub(0)
    return (base, scale, sub)

def merged_line(dt1, dt2, dt3):
    d = merge2(merge2(one_type(dt1), one_type(dt2)), one_type(dt3))
    return '01: sqltype: %s scale: %d subtype: %d len: %d' % (SQLUDA[d[0]], d[1], d[2], LEN[d[0]])

