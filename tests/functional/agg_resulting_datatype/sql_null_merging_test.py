@pytest.mark.version('>=4.0')
@pytest.mark.ai
def test_2(act: Action):
    # SQL_NULL input parameters: only 'nullness' matters, value is ignored;
    # and '?' can / can not be merged inside various DTS aggregations.
    with act.db.connect() as con:
        cur = con.cursor()
        cur.execute('create table g_null_test(c_small smallint)')
        con.commit()
        cur.execute('insert into g_null_test values(1)')
        con.commit()

        # '?' IS NULL: param is only about nullness
        cur.execute('select ? is null from rdb$database', (None,))
        assert cur.fetchone()[0] == True
        cur.execute('select ? is null from rdb$database', (123,))
        assert cur.fetchone()[0] == False

        # bare '?': no type info at all
        with pytest.raises(DatabaseError, match='Data type unknown'):
            cur.execute('select ? from rdb$database', (None,))

        # '?' in UNION position can not be resolved against other DTS members
        with pytest.raises(DatabaseError, match='Data type unknown'):
            cur.execute('select c_small from g_null_test union all select ? from g_null_test', (None,))

        # but '?' IS merged inside CASE and COALESCE:
        cur.execute('select case when 1=0 then c_small else ? end from g_null_test', (123,))
        assert cur.fetchone()[0] == 123
        cur.execute('select case when 1=1 then c_small else ? end from g_null_test', (123,))
        assert cur.fetchone()[0] == 1
