@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, tmp_path: Path):

    ts_name = 'TS1' # name of tablespace in DB.

    # Random names of files that will be used for storage TS data:
    rnd_name_1 = 'ts_1_' + generate_random_string(20)
    rnd_name_2 = 'ts_2_' + generate_random_string(20)
    rnd_name_3 = 'ts_missed_' + generate_random_string(20)

    ts_file_1 = tmp_path / rnd_name_1
    ts_file_2 = tmp_path / rnd_name_2
    ts_file_missing = tmp_path / rnd_name_3

    # +++++++++++++++++++++++++++++++++ check #1 +++++++++++++++++++++++++++++++++
    # create branch: tablespace does not exist yet
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"""
        set bail on;
        set list on;
        create or alter tablespace {ts_name} file '{ts_file_1}';
        commit;

        create table test_table(id int);
        commit;

        alter table test_table set tablespace {ts_name};
        commit;

        insert into test_table values (1);
        insert into test_table values (2);
        commit;

        select rdb$tablespace_name as ts_name, lower(rdb$file_name) as ts_file
        from rdb$tablespaces
        where rdb$tablespace_name = upper('{ts_name}');

        select count(*) as cnt from test_table;
    """

    expected_stdout = f"""
        TS_NAME {ts_name.upper()}
        TS_FILE {str(ts_file_1).lower()}
        CNT     2
    """

    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # The file must have been created by the CREATE OR ALTER statement
    assert ts_file_1.is_file(), f'Tablespace file {ts_file_1.name} was not created'

    # +++++++++++++++++++++++++++++++++ check #2a +++++++++++++++++++++++++++++++++
    # alter branch: replace path with a copy of the file
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    shutil.copyfile(ts_file_1, ts_file_2)

    test_sql = f"""
        set bail on;
        set list on;
        create or alter tablespace {ts_name} file '{ts_file_2}';
        commit;

        select lower(rdb$file_name) as ts_file
        from rdb$tablespaces
        where rdb$tablespace_name = upper('{ts_name}');

        select count(*) as cnt from test_table;
    """

    expected_stdout = f"""
        TS_FILE {str(ts_file_2).lower()}
        CNT     2
    """
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # +++++++++++++++++++++++++++++++++ check #2b +++++++++++++++++++++++++++++++++
    # Old file (ts_file_1) is no longer associated with DB: drop it.
    # Data must remain accessible from the new file.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    ts_file_1.unlink()

    test_sql = """
        set list on;
        insert into test_table(id) select -id from test_table;
        select count(*) as cnt from test_table;
    """
    expected_stdout = """
        CNT     4
    """

    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input = test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()


    # +++++++++++++++++++++++++++++++++ check #3 +++++++++++++++++++++++++++++++++
    # alter branch with non-existent target file must fail
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"""
        create or alter tablespace {ts_name} file '{ts_file_missing}';
        commit;
    """

    expected_stdout = f"""
        Statement failed, SQLSTATE = 08001
        unsuccessful metadata update
        -CREATE OR ALTER TABLESPACE {ts_name.upper()} failed
        -Tablespace file "{ts_file_missing}" does not exist
    """
    
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input = test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
