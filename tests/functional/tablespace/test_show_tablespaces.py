@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, tmp_path: Path):

    # Names of tablespaces, deliberately created below in NON-alphabetical
    # order (ts_b, then ts_a, then ts_c):
    ts_name_a = 'TS_A'
    ts_name_b = 'TS_B'
    ts_name_c = 'TS_C'

    # Random names of files that will be used for storage TS data:
    rnd_name_a = 'ts_show_a_' + generate_random_string(20)
    ts_file_a = tmp_path / rnd_name_a

    rnd_name_b = 'ts_show_b_' + generate_random_string(20)
    ts_file_b = tmp_path / rnd_name_b

    rnd_name_c = 'ts_show_c_' + generate_random_string(20)
    ts_file_c = tmp_path / rnd_name_c

    # +++++++++++++++++++++++++++++++++ check #1 +++++++++++++++++++++++++++++++++
    # SHOW TABLESPACES: names in alphabetical order, no PRIMARY in the list
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    init_sql = f"""
        set bail on;
        create tablespace {ts_name_b} file '{ts_file_b}';
        create tablespace {ts_name_a} file '{ts_file_a}';
        create tablespace {ts_name_c} file '{ts_file_c}';
        commit;
    """
    expected_stdout = ''
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=init_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    test_sql = "show tablespaces;"
    expected_stdout = f"""
        {ts_name_a}
        {ts_name_b}
        {ts_name_c}
    """
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # +++++++++++++++++++++++++++++++++ check #2 +++++++++++++++++++++++++++++++++
    # SHOW TABLESPACE <name>: detailed info about user tablespace
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"show tablespace {ts_name_a};"
    expected_stdout = f"""
        {ts_name_a} FILE {ts_file_a} ONLINE READ WRITE
    """
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
