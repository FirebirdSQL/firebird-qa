"""
ID:          functional.tablespace.test_alter_index_ts_visibility
TITLE:       Migrated index must be visible to the optimizer after 'ALTER INDEX ... SET TABLESPACE'
DESCRIPTION:
    [generated by zcode.ai]
    ALTER INDEX ... SET TABLESPACE performs "index migration": a new index is
    built in the target tablespace and the index root page slot is switched to
    the irt_migrate state, with the old index kept in the back slot. Migration
    finalization (setNormal + kill the back slot) runs lazily, on the first
    index access by any transaction that is other than the migration owner.

    Test creates a table with TWO indexes, fills it with rows, moves one of the
    indexes to another tablespace and, from NEW connections (whose transactions
    started after the migration DDL was committed), checks:
    1. plan of statement that uses the NOT migrated (control) index contains
       this index (sanity check);
    2. plan of statement that uses the MIGRATED index must contain this index
       too (it must NOT be omitted by BTR_all() / optimizer after migration
       was committed) and must NOT be NATURAL;
    3. rows inserted after the migration must be correctly found via the
       migrated index; total row count must be preserved.

    Before the fix getIndexSlot() redirected the irt_migrate slot to its back
    slot for EVERY transaction other than the migration owner, even after the
    migration had been committed. As a result the new index was never exposed,
    migration finalization never ran, and BTR_all() omitted the index entirely:
    every statement prepared after the migration performed NATURAL scan instead
    of using the migrated index (and the migration itself never completed).

    TEST_PLAN:
    1. Create tablespace, table with two indexes, insert ROWS_COUNT rows.
    2. ALTER INDEX idx_t_test SET TABLESPACE <new_ts>; commit.
    3. From fresh connections: execute selects that use both indexes and check
       their plans.
    4. Insert one more row from a new connection; verify it is returned via
       the migrated index and overall row count is correct.

NOTES:
    [19.11.2026] pzotov
    Test was generated by AI (ZCode / GLM).

    FB commit (2026-11-16):
    https://github.com/FirebirdSQL/firebird/commit/ba8de4e3fc2dce0cb6b0c7716562f11900289564
    "Fix index visibility after ALTER INDEX ... SET TABLESPACE"

    Confirmed difference on:
    * 6.0.0.2471-3dc55fb (bug: plan for the migrated index became NATURAL).
    * 6.0.0.2496-f0accd6 (fix presents: both plans use indexes, all rows found)
"""

import pytest
from firebird.qa import *

db = db_factory()

act = python_act('db')

ROWS_COUNT = 1000

#-----------------------------------------------------------

@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, tmp_path):

    ts_file = tmp_path / 'ts_index_migration.dat'

    with act.db.connect() as con:
        cur = con.cursor()
        cur.execute(f"create tablespace ts_migration file '{ts_file}'")
        cur.execute('create table t_test(id int not null, s varchar(20))')
        cur.execute('create index idx_t_test on t_test(id)')
        cur.execute('create index idx_control on t_test(s)')
        con.commit()
        cur.execute(
            "execute block as declare variable i int = 0; begin"
            f" while (i < {ROWS_COUNT}) do begin i = i + 1;"
            " insert into t_test(id, s) values(:i, 'row_' || :i);"
            " end end"
        )
        con.commit()
        # migration transaction is committed here; finalization must be
        # performed by ANY transaction that sees it as committed:
        cur.execute('alter index idx_t_test set tablespace ts_migration')
        con.commit()

    # check plans from FRESH connections, so that statements are compiled
    # (and BTR_all() runs) strictly after the migration was committed:

    with act.db.connect() as con:
        cur = con.cursor()
        ps = cur.prepare("select id from t_test where s = 'row_42'")
        cur.execute(ps)
        cur.fetchall()
        plan_control = ps.plan

        ps = cur.prepare('select id from t_test where id = 42')
        cur.execute(ps)
        rows_migrated = cur.fetchall()
        plan_migrated = ps.plan

    assert 'IDX_CONTROL' in plan_control.upper(), f'Plan for control index: {plan_control}'
    assert 'NATURAL' not in plan_control.upper(), f'Plan for control index: {plan_control}'

    assert 'IDX_T_TEST' in plan_migrated.upper(), \
        f'Plan for migrated index must use it, but it was: {plan_migrated}'
    assert 'NATURAL' not in plan_migrated.upper(), \
        f'Plan for migrated index must NOT be NATURAL, but it was: {plan_migrated}'
    assert rows_migrated == [(42,)], f'Unexpected rows: {rows_migrated}'

    # rows inserted AFTER migration must be found via migrated index:
    with act.db.connect() as con:
        cur = con.cursor()
        cur.execute("insert into t_test(id, s) values (?, ?)", (ROWS_COUNT + 1, f'row_{ROWS_COUNT + 1}'))
        con.commit()

    with act.db.connect() as con:
        cur = con.cursor()
        ps = cur.prepare(f'select id, s from t_test where id = {ROWS_COUNT + 1}')
        cur.execute(ps)
        rows_new = cur.fetchall()
        plan_after_dml = ps.plan

        cur.execute('select count(*) from t_test')
        rows_count = cur.fetchall()

    assert rows_new == [(ROWS_COUNT + 1, f'row_{ROWS_COUNT + 1}')], f'Unexpected rows: {rows_new}'
    assert 'NATURAL' not in plan_after_dml.upper(), f'Plan after DML: {plan_after_dml}'
    assert rows_count == [(ROWS_COUNT + 1,)], f'Unexpected rows count: {rows_count}'
