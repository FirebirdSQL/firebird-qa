@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, tmp_path: Path):

    ts_name_1 = 'TS1' # name of first tablespace in DB.
    ts_name_2 = 'TS2' # name of second tablespace in DB.

    # Random names of files that will be used for storage TS data:
    rnd_name_1 = 'ts_ddl_trg_1_' + generate_random_string(20)
    ts_file_1 = tmp_path / rnd_name_1

    rnd_name_2 = 'ts_ddl_trg_2_' + generate_random_string(20)
    ts_file_2 = tmp_path / rnd_name_2

    # ALTER TABLESPACE requires that its target file exists, otherwise
    # 'Tablespace file ... does not exist' error occurs:
    ts_file_alter_target = tmp_path / ('ts_ddl_trg_target_' + generate_random_string(20))
    ts_file_alter_target.write_text('', encoding = 'utf-8')

    # +++++++++++++++++++++++++++++++++ check #1 +++++++++++++++++++++++++++++++++
    # Create log table and triggers. Each trigger inserts its letter into
    # the log table.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    init_sql = f"""
        set bail on;
        create table log_ts_trigger (op varchar(10));
        commit;

        set term ^;

        create trigger trg_ts_create before create tablespace
        as
        begin
            insert into log_ts_trigger values ('C');
        end^

        create trigger trg_ts_alter before alter tablespace
        as
        begin
            insert into log_ts_trigger values ('A');
        end^

        create trigger trg_ts_drop before drop tablespace
        as
        begin
            insert into log_ts_trigger values ('D');
        end^

        set term ;^
        commit;
    """
