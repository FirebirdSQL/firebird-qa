    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=init_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    def check_state(cnt_create: int, cnt_alter: int, cnt_drop: int):
        """Verify how many times each of the triggers has fired so far."""
        db_conn = act.db.connect()
        try:
            cur = db_conn.cursor()
            cur.execute("select op, count(*) from log_ts_trigger group by op")
            actual = { row[0].strip(): row[1] for row in cur.fetchall() }
        finally:
            db_conn.close()

        expected = { 'C': cnt_create, 'A': cnt_alter, 'D': cnt_drop }
        for op, want in expected.items():
            got = actual.get(op, 0)
            assert got == want, f"Trigger log for '{op}': got {got}, expected {want}"

    # ... no trigger has fired yet:
    check_state(0, 0, 0)

