    ts_name_u3_64 = 'TS3B_' + '日' * 59    # chars: 64, bytes: 182, 182 % 64 = 54
    ts_name_umix_64 = 'A' * 10 + 'А' * 10 + '日' * 10 + '😀' * 34
    # chars: 64, bytes: 10 + 20 + 30 + 136 = 196, 196 % 64 = 4

    for ts_name_u in (ts_name_u2_64, ts_name_u3_64, ts_name_umix_64):
        assert len(ts_name_u) == 64
        assert len(ts_name_u.encode('utf-8')) % 64 != 0

        rnd_name_u = 'ts_u64_' + generate_random_string(20)
        ts_file_u = tmp_path / rnd_name_u

        test_sql = f"""
            create tablespace \"{ts_name_u}\" file '{ts_file_u}';
            commit;
        """

        sql_file = tmp_path / ('ts_u64_' + generate_random_string(10) + '.sql')
        sql_file.write_text(test_sql, encoding = 'utf-8')

        expected_stdout = f"""
            Statement failed, SQLSTATE = 42000
            Dynamic SQL Error
            -SQL error code = -104
            -Name longer than database column size
            -At line 1, column 19
            After line 0 in file {sql_file}
        """

        act.expected_stdout = expected_stdout
        act.isql(switches = ['-q'], charset = 'utf8', input_file = sql_file,
                 combine_output = True, io_enc = locale.getpreferredencoding())
        assert act.clean_stdout == act.clean_expected_stdout
        act.reset()
