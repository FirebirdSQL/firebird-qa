@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, tmp_path: Path):

    ts_name = 'TS1'         # name of "ordinary" tablespace in DB.
    ts_name_prim = 'PRIMARY' # reserved name of system tablespace.

    # Tablespaces with names of exactly 63 and 64 characters:
    ts_name_63 = ('TS63_' + generate_random_string(58)).upper()
    ts_name_64 = ('TS64_' + generate_random_string(59)).upper()
    assert len(ts_name_63) == 63
    assert len(ts_name_64) == 64

    # Random names of files that will be used for storage TS data:
    rnd_name = 'ts_dup_' + generate_random_string(20)
    ts_file = tmp_path / rnd_name

    rnd_name_63 = 'ts_63_' + generate_random_string(20)
    ts_file_63 = tmp_path / rnd_name_63

    rnd_name_64 = 'ts_64_' + generate_random_string(20)
    ts_file_64 = tmp_path / rnd_name_64

    # +++++++++++++++++++++++++++++++++ check #1 +++++++++++++++++++++++++++++++++
    # plain (without IF NOT EXISTS) duplicate CREATE TABLESPACE must fail.
    # Error message is BIZARRE (see docstring), we only pin it.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"""
        set bail on;
        create tablespace {ts_name} file '{ts_file}';
        commit;
    """
    expected_stdout = ''
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    test_sql = f"""
        create tablespace {ts_name} file '{ts_file}';
        commit;
    """
    expected_stdout = f"""
        Statement failed, SQLSTATE = 42000
        unsuccessful metadata update
        -CREATE TABLESPACE {ts_name.upper()} failed
        -The constant "{ts_name.upper()}" must be initialized by a constant expression
    """
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # +++++++++++++++++++++++++++++++++ check #2a +++++++++++++++++++++++++++++++++
    # PRIMARY (unquoted) is a reserved name and must not be usable.
    # Error message is BIZARRE (see docstring), we only pin it.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"""
        create tablespace {ts_name_prim} file '{ts_file}';
        commit;
    """
    expected_stdout = f"""
        Statement failed, SQLSTATE = 42000
        unsuccessful metadata update
        -CREATE TABLESPACE {ts_name_prim} failed
        -The constant "{ts_name_prim}" must be initialized by a constant expression
    """
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # +++++++++++++++++++++++++++++++++ check #2b +++++++++++++++++++++++++++++++++
    # PRIMARY (quoted) is a reserved name too: engine reports it UNquoted.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"""
        create tablespace "{ts_name_prim}" file '{ts_file}';
        commit;
    """
    expected_stdout = f"""
        Statement failed, SQLSTATE = 42000
        unsuccessful metadata update
        -CREATE TABLESPACE {ts_name_prim} failed
        -The constant "{ts_name_prim}" must be initialized by a constant expression
    """
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # +++++++++++++++++++++++++++++++++ check #3 +++++++++++++++++++++++++++++++++
    # name of exactly 63 characters is allowed
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"""
        set bail on;
        set list on;
        create tablespace {ts_name_63} file '{ts_file_63}';
        commit;

        select count(*) as cnt
        from rdb$tablespaces
        where rdb$tablespace_name = upper('{ts_name_63}');
    """
    expected_stdout = f"""
        CNT 1
    """
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # +++++++++++++++++++++++++++++++++ check #4 +++++++++++++++++++++++++++++++++
    # name of 64 characters must be rejected.
    # NOTE: statement is deliberately the FIRST line of isql input, so the
    # parser reports 'At line 1, column 19'.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"create tablespace {ts_name_64} file '{ts_file_64}'; commit;"
    expected_stdout = f"""
        Statement failed, SQLSTATE = 42000
        Dynamic SQL Error
        -SQL error code = -104
        -Name longer than database column size
        -At line 1, column 19
    """
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
