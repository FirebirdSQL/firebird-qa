@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, tmp_path: Path):

    ts_name = 'TS1'         # name of "ordinary" tablespace in DB.
    ts_name_prim = 'PRIMARY' # reserved name of system tablespace.

    # Tablespaces with names of exactly 63 and 64 characters:
    ts_name_63 = ('TS63_' + generate_random_string(58)).upper()
    ts_name_64 = ('TS64_' + generate_random_string(59)).upper()
    assert len(ts_name_63) == 63
    assert len(ts_name_64) == 64

    # Random names of files that will be used for storage TS data:
    rnd_name = 'ts_dup_' + generate_random_string(20)
    ts_file = tmp_path / rnd_name

    rnd_name_63 = 'ts_63_' + generate_random_string(20)
    ts_file_63 = tmp_path / rnd_name_63

    rnd_name_64 = 'ts_64_' + generate_random_string(20)
    ts_file_64 = tmp_path / rnd_name_64

    # +++++++++++++++++++++++++++++++++ check #1 +++++++++++++++++++++++++++++++++
    # plain (without IF NOT EXISTS) duplicate CREATE TABLESPACE must fail.
    # Error message is BIZARRE (see docstring), we only pin it.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"""
        set bail on;
        create tablespace {ts_name} file '{ts_file}';
        commit;
    """
    expected_stdout = ''
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    test_sql = f"""
        create tablespace {ts_name} file '{ts_file}';
        commit;
    """
    expected_stdout = f"""
        Statement failed, SQLSTATE = 42000
        unsuccessful metadata update
        -CREATE TABLESPACE {ts_name.upper()} failed
        -The constant "{ts_name.upper()}" must be initialized by a constant expression
    """
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # +++++++++++++++++++++++++++++++++ check #2a +++++++++++++++++++++++++++++++++
    # PRIMARY (unquoted) is a reserved name and must not be usable.
    # Error message is BIZARRE (see docstring), we only pin it.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"""
        create tablespace {ts_name_prim} file '{ts_file}';
        commit;
    """
    expected_stdout = f"""
        Statement failed, SQLSTATE = 42000
        unsuccessful metadata update
        -CREATE TABLESPACE {ts_name_prim} failed
        -The constant "{ts_name_prim}" must be initialized by a constant expression
    """
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # +++++++++++++++++++++++++++++++++ check #2b +++++++++++++++++++++++++++++++++
    # PRIMARY (quoted) is a reserved name too: engine reports it UNquoted.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"""
        create tablespace "{ts_name_prim}" file '{ts_file}';
        commit;
    """
    expected_stdout = f"""
        Statement failed, SQLSTATE = 42000
        unsuccessful metadata update
        -CREATE TABLESPACE {ts_name_prim} failed
        -The constant "{ts_name_prim}" must be initialized by a constant expression
    """
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # +++++++++++++++++++++++++++++++++ check #3 +++++++++++++++++++++++++++++++++
    # name of exactly 63 characters is allowed
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"""
        set bail on;
        set list on;
        create tablespace {ts_name_63} file '{ts_file_63}';
        commit;

        select count(*) as cnt
        from rdb$tablespaces
        where rdb$tablespace_name = upper('{ts_name_63}');
    """
    expected_stdout = f"""
        CNT 1
    """
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # +++++++++++++++++++++++++++++++++ check #4 +++++++++++++++++++++++++++++++++
    # name of 64 characters must be rejected.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"""
        create tablespace {ts_name_64} file '{ts_file_64}';
        commit;
    """
    expected_stdout = f"""
        Statement failed, SQLSTATE = 42000
        Dynamic SQL Error
        -SQL error code = -104
        -Name longer than database column size
        -At line 1, column 19
    """
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # +++++++++++++++++++++++++++++++++ check #5 +++++++++++++++++++++++++++++++++
    # names with char-length exactly 63 built from non-ASCII characters
    # requiring 2, 3 and 4 bytes per character in UTF-8 (and from their mix
    # with ASCII): all of them must be created successfully and stored
    # byte-intact.
    # Byte-length of each name must NOT be divisible by 63 without remainder
    # (otherwise some hypothetical truncation could remain undetected).
    # NOTE: each SQL script is written to a temporary FILE which is passed
    # to isql with '-i' switch: scripts with non-ASCII content must NOT be
    # fed via stdin/pipe, otherwise we could encounter problems on Linux.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

    # Cyrillic capital letter 'А' (U+0410): 2 bytes per char in UTF-8.
    # CJK character '日' (U+65E5): 3 bytes per char in UTF-8.
    # Emoji '😀' (U+1F600): 4 bytes per char in UTF-8.

    ts_name_u2_63 = 'TS2B_' + 'А' * 58    # chars: 63, bytes: 121, 121 % 63 = 58
    ts_name_u3_63 = 'TS3B_' + '日' * 58    # chars: 63, bytes: 179, 179 % 63 = 53
    ts_name_umix_63 = 'A' * 10 + 'А' * 10 + '日' * 10 + '😀' * 33
    # chars: 63, bytes: 10 + 20 + 30 + 132 = 192, 192 % 63 = 3

    for ts_name_u in (ts_name_u2_63, ts_name_u3_63, ts_name_umix_63):
        assert len(ts_name_u) == 63
        assert len(ts_name_u.encode('utf-8')) % 63 != 0

        rnd_name_u = 'ts_u63_' + generate_random_string(20)
        ts_file_u = tmp_path / rnd_name_u

        test_sql = f"""
            set bail on;
            set list on;
            create tablespace "{ts_name_u}" file '{ts_file_u}';
            commit;

            select count(*) as cnt
            from rdb$tablespaces
            where rdb$tablespace_name = '{ts_name_u}';
        """
        expected_stdout = f"""
            CNT 1
        """

        sql_file = tmp_path / ('ts_u63_' + generate_random_string(10) + '.sql')
        sql_file.write_text(test_sql, encoding = 'utf-8')

        act.expected_stdout = expected_stdout
        act.isql(switches = ['-q'], charset = 'utf8', input_file = sql_file,
                 combine_output = True, io_enc = locale.getpreferredencoding())
        assert act.clean_stdout == act.clean_expected_stdout
        act.reset()

    # +++++++++++++++++++++++++++++++++ check #6 +++++++++++++++++++++++++++++++++
    # the same names but with char-length exactly 64 (byte-length NOT
    # divisible by 64) must be rejected with the same error as ASCII-only
    # ones.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++

