import shutil
import pytest
import random
import string
from pathlib import Path
from firebird.driver import TPB, DatabaseError
from firebird.qa import *

db = db_factory()
act = python_act('db')

nowait_tpb = TPB(lock_timeout = 0).get_buffer()

#----------------------------------

def generate_random_string(length):
    # Combine letters and digits (abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789)
    characters = string.ascii_letters + string.digits
    
    # Randomly choose characters and join them into a string
    return ''.join(random.choices(characters, k=length))

#----------------------------------

def expect_in_use(conn, stmt: str, ts_name: str):
    """Execute DDL statement on NO WAIT connection, expect 'in use' lock conflict."""
    conn.begin(tpb = nowait_tpb)
    try:
        with pytest.raises(DatabaseError) as exc_info:
            conn.cursor().execute(stmt)
        e = exc_info.value
        assert e.sqlstate == '42000', f'Unexpected SQLSTATE: {e.sqlstate}'
        assert f'object TABLESPACE "{ts_name}" is in use' in str(e), f'Unexpected error text: {e}'
    finally:
        conn.rollback()

#----------------------------------

@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, tmp_path: Path):

    ts_name_1 = 'TS1' # name of first tablespace in DB.
    ts_name_2 = 'TS2' # name of second tablespace in DB.

    # Random names of files that will be used for storage TS data:
    rnd_name_1 = 'ts_lock_1_' + generate_random_string(20)
    ts_file_1 = tmp_path / rnd_name_1

    rnd_name_2 = 'ts_lock_2_' + generate_random_string(20)
    ts_file_2 = tmp_path / rnd_name_2

    # +++++++++++++++++++++++++++++++++ check #1 +++++++++++++++++++++++++++++++++
    # setup: two tablespaces, two tables, T1 moved into TS1 (committed)
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    init_sql = f"""
        set bail on;
        create tablespace {ts_name_1} file '{ts_file_1}';
        create tablespace {ts_name_2} file '{ts_file_2}';
        commit;

        create table t1(id int);
        create table t2(id int);
        commit;

        insert into t1 values (1);
        insert into t1 values (2);
        commit;

        alter table t1 set tablespace {ts_name_1};
        commit;
    """
    expected_stdout = ''
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=init_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # A valid target file for ALTER TABLESPACE SET FILE:
    ts_file_1_copy = tmp_path / ('ts_lock_copy_' + generate_random_string(20))
    shutil.copyfile(ts_file_1, ts_file_1_copy)

    # +++++++++++++++++++++++++++++++++ check #2 +++++++++++++++++++++++++++++++++
    # ALTER TABLESPACE vs open reader: connection that reads data located
    # in TS1 (open transaction) must block ALTER of that tablespace.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    reader = act.db.connect()
    try:
        reader.begin(tpb = nowait_tpb)
        cur = reader.cursor()
        cur.execute('select * from t1')
        cur.fetchall()

        alterer = act.db.connect()
        try:
            expect_in_use(
                alterer,
                f"alter tablespace {ts_name_1} set file to '{ts_file_1_copy}'",
                ts_name_1,
            )
        finally:
            alterer.close()
    finally:
        reader.rollback()
        reader.close()

    # +++++++++++++++++++++++++++++++++ check #3 +++++++++++++++++++++++++++++++++
    # after the reader is gone, ALTER must succeed
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    alterer = act.db.connect()
    try:
        alterer.begin(tpb = nowait_tpb)
        alterer.cursor().execute(f"alter tablespace {ts_name_1} set file to '{ts_file_1_copy}'")
        alterer.commit()
    finally:
        alterer.close()

    # +++++++++++++++++++++++++++++++++ check #4 +++++++++++++++++++++++++++++++++
    # DROP TABLESPACE vs uncommitted move INTO it: attachment that has an
    # uncommitted ALTER TABLE ... SET TABLESPACE TS2 must block DROP of TS2.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    mover = act.db.connect()
    try:
        mover.begin(tpb = nowait_tpb)
        mover.cursor().execute(f'alter table t2 set tablespace {ts_name_2}')  # NOT committed

        dropper = act.db.connect()
        try:
            expect_in_use(dropper, f'drop tablespace {ts_name_2}', ts_name_2)
        finally:
            dropper.close()
    finally:
        mover.rollback()
        mover.close()

    # +++++++++++++++++++++++++++++++++ check #5 +++++++++++++++++++++++++++++++++
    # after the move is rolled back, TS2 is empty and DROP must succeed
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    dropper = act.db.connect()
    try:
        dropper.begin(tpb = nowait_tpb)
        dropper.cursor().execute(f'drop tablespace {ts_name_2}')
        dropper.commit()
    finally:
        dropper.close()

    # +++++++++++++++++++++++++++++++++ check #6 +++++++++++++++++++++++++++++++++
    # data of T1 must still be accessible (from the copied file)
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    checker = act.db.connect()
    try:
        checker.begin(tpb = nowait_tpb)
        cur = checker.cursor()
        cur.execute('select count(*) from t1')
        assert cur.fetchone()[0] == 2
    finally:
        checker.rollback()
        checker.close()
