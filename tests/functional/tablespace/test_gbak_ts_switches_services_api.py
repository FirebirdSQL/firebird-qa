import re
import pytest
from pathlib import Path
from firebird.qa import *

import firebird.driver as fbdrv
from firebird.driver.core import ServerAction, SrvRestoreOption, SPBItem, XpbKind

TS_NAME = 'TS_SVC'
TABLE_NAME = 'T_SVC'

db = db_factory()
substitutions = [('[ \t]+', ' ')]
act = python_act('db')

expected_stdout = f"""
    REL_TS                          {TS_NAME}
    ROWS_CNT                        100
"""


def services_restore(act: Action, backup_file, db_name, spb_builder=None, options=0x2000):
    """Run isc_action_svc_restore with custom SPB items.

    spb_builder: callable(spb, encoding) which inserts additional items;
    options: value for isc_spb_options (0x2000 = isc_spb_res_create).
    """
    with act.connect_server(user = act.db.user, password = act.db.password) as srv:
        enc = srv.encoding
        api = fbdrv.get_api()
        with api.util.get_xpb_builder(XpbKind.SPB_START) as spb:
            spb.insert_tag(ServerAction.RESTORE)
            spb.insert_string(SrvRestoreOption.FILE, str(backup_file), encoding = enc)
            spb.insert_string(SPBItem.DBNAME, str(db_name), encoding = enc)
            if spb_builder:
                spb_builder(spb, enc)
            spb.insert_int(SPBItem.OPTIONS, options)
            srv._reset_output()
            srv._svc.start(spb.get_buffer())
        srv.wait()
        return [line for line in srv]


def check_restored(act: Action, restored_dsn):
    """Print TS name and row count of the restored DB (output is checked by expected_stdout)."""
    act.isql(switches=['-q'], connect_db=False, input=f"""
        connect '{restored_dsn}' user '{act.db.user}' password '{act.db.password}';
        set list on;
        select
            (select x.rdb$tablespace_name from rdb$tablespaces x where x.rdb$system_flag <> 1) as rel_ts,
            (select count(*) from {TABLE_NAME}) as rows_cnt
            from rdb$database;
            exit;
    """)
    act.expected_stdout = expected_stdout
    assert act.clean_stdout == act.clean_expected_stdout, \
        f'Unexpected metadata/data of restored database:\n{act.stdout}'
    act.reset()


@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, tmp_path: Path):

    # dsn for a database file = same host part as act.db.dsn has
    # NB: split(':', 1) because the path part itself contains ':' of the drive letter
    def make_dsn(f: Path) -> str:
        return act.db.dsn.split(':', 1)[0] + ':' + str(f)

    ts_file = tmp_path / 'ts_svc.dat'          # original path, used by scenario 1 and -ts_orig
    ts_map_file = tmp_path / 'ts_svc_mapped.dat'  # fresh path for the mapping file scenario
    fbk_file = tmp_path / 'ts_svc.fbk'
    map_txt = tmp_path / 'ts_svc_map.txt'

    restored_path_db = tmp_path / 'ts_svc_res_path.fdb'
    restored_map_db = tmp_path / 'ts_svc_res_map.fdb'
    restored_orig_db = tmp_path / 'ts_svc_res_orig.fdb'

    act.isql(switches=['-q'], input=f"""
        create tablespace {TS_NAME} file '{ts_file}';
        commit;
        create table {TABLE_NAME} (id int not null, b varchar(100)) tablespace {TS_NAME};
        commit;
        insert into {TABLE_NAME} select row_number() over(), rpad('x', 50) from rdb$types rows 100;
        commit;
    """)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    act.gbak(switches=['-b', act.db.dsn, str(fbk_file)], combine_output=True)
    assert act.return_code == 0, f'gbak -b failed:\n{act.stdout}\n{act.stderr}'
    act.reset()

    # ########### scenario 1: isc_spb_res_ts_path (tag 25, two strings: name, path) ###########

    # restore (re)creates the tablespace file at the given path, so remove the
    # file which still exists there since CREATE TABLESPACE
    if ts_file.exists():
        ts_file.unlink()

    out = services_restore(
        act, fbk_file, restored_path_db,
        spb_builder = lambda spb, enc: (
            spb.insert_string(25, TS_NAME, encoding = enc),          # isc_spb_res_ts_path: name
            spb.insert_string(25, str(ts_file), encoding = enc),     # isc_spb_res_ts_path: path
        )
    )
    assert out == [], f'Service restore returned unexpected output:\n{out}'
    check_restored(act, make_dsn(restored_path_db))

    # ########### scenario 2: isc_spb_res_ts_mapping_file (tag 24, mapping file) ###########

    # NB: the original tablespace file has been re-created by the restore of scenario 1,
    # so this scenario maps TS_SVC to a FRESH path which does not exist yet
    map_txt.write_text(f'{TS_NAME} {ts_map_file}\n', encoding='utf-8')

    out = services_restore(
        act, fbk_file, restored_map_db,
        spb_builder = lambda spb, enc: spb.insert_string(24, str(map_txt), encoding = enc),
    )
    assert out == [], f'Service restore returned unexpected output:\n{out}'
    check_restored(act, make_dsn(restored_map_db))

    # ########### scenario 3: isc_spb_res_ts_org_paths (bit 0x080000 inside isc_spb_options) ###########

    # -ts_orig recreates the tablespace at its ORIGINAL location, so remove it first
    if ts_file.exists():
        ts_file.unlink()

    out = services_restore(act, fbk_file, restored_orig_db, options = 0x2000 | 0x080000)
    assert out == [], f'Service restore returned unexpected output:\n{out}'
    assert ts_file.exists(), f'-ts_orig did not recreate the tablespace file {ts_file}'
    check_restored(act, make_dsn(restored_orig_db))
