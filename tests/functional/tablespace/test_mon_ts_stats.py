@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, tmp_path: Path):

    ts_name = 'TS1' # name of tablespace in DB.
    t_name = 'TEST_TABLE'

    # Random name of file that will be used for storage TS data:
    rnd_name = 'ts_mon_stats_' + generate_random_string(20)
    ts_file = tmp_path / rnd_name

    # +++++++++++++++++++++++++++++++++ check #1 +++++++++++++++++++++++++++++++++
    # create tablespace and table in it (DML is done below, on the python
    # connection -- see docstring)
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    init_sql = f"""
        set bail on;
        create tablespace {ts_name} file '{ts_file}';
        commit;

        create table {t_name.lower()}(id int, v varchar(20)) tablespace {ts_name};
        commit;
    """
    expected_stdout = ''
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=init_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    db_conn = act.db.connect()
    try:
        cur = db_conn.cursor()

        # Perform DML and reads on THIS connection (see docstring):
        cur.execute(f"insert into {t_name.lower()} values (1, 'one')")
        cur.execute(f"insert into {t_name.lower()} values (2, 'two')")
        db_conn.commit()

        cur.execute(f"select count(*) from {t_name.lower()}")
        assert cur.fetchone()[0] == 2

        # +++++++++++++++++++++++++++++ check #2 +++++++++++++++++++++++++++++
        # column set (in declared order)
        # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
        cur.execute("""
            select rf.rdb$field_name
            from rdb$relation_fields rf
            where rf.rdb$relation_name = 'MON$TABLESPACE_STATS'
            order by rf.rdb$field_position
        """)
        actual_columns = [ row[0].strip() for row in cur.fetchall() ]
        assert actual_columns == EXPECTED_COLUMNS

        # +++++++++++++++++++++++++++++ check #3 +++++++++++++++++++++++++++++
        # column types
        # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
        for col_name, (f_type, f_subtype) in EXPECTED_TYPES.items():
            cur.execute("""
                select f.rdb$field_type, f.rdb$field_sub_type
                from rdb$relation_fields rf
                join rdb$fields f on rf.rdb$field_source = f.rdb$field_name
                where rf.rdb$relation_name = 'MON$TABLESPACE_STATS'
                  and rf.rdb$field_name = ?
            """, [col_name])
            row = cur.fetchone()
            assert row[0] == f_type, f'{col_name}: field_type = {row[0]}, expected {f_type}'
            assert row[1] == f_subtype, f'{col_name}: field_sub_type = {row[1]}, expected {f_subtype}'

        # +++++++++++++++++++++++++++++ check #4 +++++++++++++++++++++++++++++
        # rows exist for PRIMARY and for the user tablespace
        # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
        cur.execute("""
            select distinct m.mon$tablespace_name
            from mon$tablespace_stats m
        """)
        ts_names = { row[0].strip() for row in cur.fetchall() }
        assert 'PRIMARY' in ts_names, f'No MON$TABLESPACE_STATS rows for PRIMARY. Got: {ts_names}'
        assert ts_name in ts_names, f'No MON$TABLESPACE_STATS rows for {ts_name}. Got: {ts_names}'

        # +++++++++++++++++++++++++++++ check #5 +++++++++++++++++++++++++++++
        # every MON$IO_STAT_ID refers to existing MON$IO_STATS record
        # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
        cur.execute("""
            select count(*)
            from mon$tablespace_stats m
            left join mon$io_stats i on m.mon$io_stat_id = i.mon$stat_id
            where i.mon$stat_id is null
        """)
        assert cur.fetchone()[0] == 0, 'MON$IO_STAT_ID values not found in MON$IO_STATS'

        # +++++++++++++++++++++++++++++ check #6 +++++++++++++++++++++++++++++
        # IO counters for the user tablespace reflect activity
        # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
        cur.execute(f"""
            select
                coalesce(max(i.mon$page_fetches), 0),
                coalesce(max(i.mon$page_writes), 0)
            from mon$tablespace_stats m
            join mon$io_stats i on m.mon$io_stat_id = i.mon$stat_id
            where m.mon$tablespace_name = upper('{ts_name}')
        """)
        page_fetches, page_writes = cur.fetchone()
        assert page_fetches > 0, f'Expected MON$PAGE_FETCHES > 0 for {ts_name}, got {page_fetches}'
        assert page_writes > 0, f'Expected MON$PAGE_WRITES > 0 for {ts_name}, got {page_writes}'

    finally:
        db_conn.close()
