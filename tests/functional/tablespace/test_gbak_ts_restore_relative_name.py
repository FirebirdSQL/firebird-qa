"""
ID:          functional.tablespace.test_gbak_ts_restore_relative_name
TITLE:       gbak restore: relative tablespace file name must be resolved on the SERVER, against the real database location
DESCRIPTION:
    [generated by zcode.ai]
    Commits:
        * 37dd4cb1057bef73fc2c7a100c0ea9b4b7ea2db5 "Support new tablespace-related gbak switches in the Services API";
        * dbac72716abd5ff8580456c60b42e8712f7d7ff1 "Resolve tablespace relative names and separators during restore
          on the server rather than at the gbak side" (FB 6.0 master, 2026-11-24).

    Before commit dbac72716, gbak resolved a RELATIVE file name given with the -TS switch
    (or via -TS_MAPPING_FILE) on the CLIENT side, against expandDatabaseName(gbl_database_file_name):
        old (src/burp/restore.epp, get_tablespace()):
            PathUtils::fixupSeparators(newFile.begin());
            if (PathUtils::isRelative(newFile.c_str())) {
                expandDatabaseName(tdgbl->gbl_database_file_name, expanded_db, NULL);
                splitLastComponent(db_path, db_file, expanded_db);
                concatPath(ts_file_name, db_path, newFile.c_str());
            }
    When the database is specified as a NETWORK DSN ("localhost/port:C:/path/db.fdb"), the string
    contains the host part, expandDatabaseName() can NOT resolve it as alias nor as a plain path,
    and the relative tablespace name was anchored to the garbage "directory" parsed out of the DSN,
    e.g. -TS TS1 sub/ts.dat for DSN "localhost/3639:C:/db/restored.fdb" produced file name
        "localhost/sub/ts.dat"            (when DSN has alias) or
        "localhost/3639:C:/db/sub/ts.dat" (when DSN has full path)
    so the restore FAILED with I/O error (or silently put the tablespace file into a wrong place).

    After the commit, gbak stores the file name as it was given, and the ENGINE resolves
    separators and relative names during restore, against the REAL filename of the database being
    restored (Tablespace::resolveFileName(), called from the system trigger before RDB$TABLESPACES
    record is stored). As result, 'sub/ts.dat' becomes '<dir_of_restored_db>/sub/ts.dat'.

    TEST_PLAN:
    1. Create DB with tablespace TS1 (absolute file path), table T1 on TS1, 100 rows; make backup.
    2. Pre-create sub-directory <tmpdir>/sub.
    3. Restore backup with network DSN and RELATIVE tablespace name:
       gbak -c <fbk> localhost/<port>:<tmpdir>/ts_restore_rel.fdb -TS TS1 sub/ts_rel.dat
       * fixed build: rc = 0, and RDB$TABLESPACES.RDB$FILE_NAME of TS1 is the absolute path
         '<tmpdir>/sub/ts_rel.dat' (separators normalized, anchored to the real DB directory);
         data of T1 is accessible.
       * bugged build: rc != 0, gbak fails with I/O error for file "localhost/sub/ts_rel.dat".

NOTES:
    [2026-11-25] pzotov
    Test was generated by AI (ZCode / GLM).
    Confirmed difference on:
        * 6.0.0.2504-b4659fc (build WITHOUT the commit) -- FAILED:
          'gbak: ERROR:I/O error during "CreateFile (create)" operation for file "localhost/sub/sub_ts_rel.dat"';
        * 6.0.0.2507-b5665a1 (contains commits 37dd4cb1 + dbac7271) -- passed:
          restore succeeds, RDB$FILE_NAME = '<tmpdir>/sub/ts_rel.dat'.
"""

import re
import pytest
from pathlib import Path
from firebird.qa import *

TS_NAME = 'TS_REL'
TABLE_NAME = 'T_REL'

db = db_factory()
substitutions = [('[ \t]+', ' ')]
act = python_act('db', substitutions = substitutions)

# NB: internal whitespace runs are preserved by clean_stdout, and the REL_FILE line
# is masked by regex substitution to a single-space form, see below
expected_stdout = f"""
    REL_TS                          {TS_NAME}
    REL_FILE <ts_file>
    ROWS_CNT                        100
"""

@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, tmp_path: Path):

    # network DSN is essential for this test: the bug is caused by the host part
    # of the DSN, which the old client-side code could not resolve
    if not act.vars['port']:
        pytest.skip('test requires network DSN with defined port')

    host = act.vars['host'] or 'localhost'
    ts_file = tmp_path / 'ts_rel_src.dat'
    fbk_file = tmp_path / 'ts_rel.fbk'
    restored_file = tmp_path / 'ts_restore_rel.fdb'
    restored_dsn = f'{host}/{act.vars["port"]}:{restored_file}'

    act.isql(switches=['-q'], input=f"""
        create tablespace {TS_NAME} file '{ts_file}';
        commit;
        create table {TABLE_NAME} (id int not null, b varchar(100)) tablespace {TS_NAME};
        commit;
        insert into {TABLE_NAME} select row_number() over(), rpad('x', 50) from rdb$types rows 100;
        commit;
    """)
    assert act.clean_stdout == act.clean_expected_stdout

    act.gbak(switches=['-b', act.db.dsn, str(fbk_file)], combine_output=True)
    assert act.return_code == 0, f'gbak -b failed:\n{act.stdout}\n{act.stderr}'
    act.reset()

    # the sub-directory must exist: the engine creates only the FILE, not its directory
    sub_dir = tmp_path / 'sub'
    sub_dir.mkdir(exist_ok=True)

    # restore with RELATIVE tablespace name via NETWORK DSN
    act.gbak(switches=['-c', str(fbk_file), restored_dsn, '-TS', TS_NAME, 'sub/ts_rel.dat'],
             combine_output=True)
    assert act.return_code == 0, \
        f'gbak -c with relative -TS name failed (old builds resolve the relative name ' \
        f'against the host part of the DSN):\n{act.stdout}\n{act.stderr}'
    act.reset()

    # verify metadata and data of the restored database
    act.isql(switches=['-q'], connect_db=False, input=f"""
        connect '{restored_dsn}' user '{act.db.user}' password '{act.db.password}';
        set list on;
        select
            (select x.rdb$tablespace_name from rdb$tablespaces x where x.rdb$system_flag <> 1) as rel_ts,
            (select x.rdb$file_name from rdb$tablespaces x where x.rdb$system_flag <> 1) as rel_file,
            (select count(*) from {TABLE_NAME}) as rows_cnt
            from rdb$database;
            exit;
    """)
    # exact (case/slash-insensitive) check of the resolved file name: the value
    # must be extracted BEFORE act.stdout is masked for the comparison below
    rel_names = re.findall(r'REL_FILE\s+(\S.*)', act.stdout, flags=re.I)

    # RDB$FILE_NAME is stored with normalized (Windows) separators and may differ by letter case
    act.stdout = re.sub(r'REL_FILE\s+\S.*', 'REL_FILE <ts_file>', act.stdout, flags=re.I)

    act.expected_stdout = expected_stdout
    assert act.clean_stdout == act.clean_expected_stdout, \
        f'Unexpected content of RDB$TABLESPACES after restore:\n{act.stdout}'

    assert rel_names, f'RDB$FILE_NAME of tablespace {TS_NAME} not found in output:\n{act.stdout}'
    stored = rel_names[0].strip().replace('/', '\\').lower()
    expected = str(tmp_path / 'sub' / 'ts_rel.dat').replace('/', '\\').lower()
    assert stored == expected, f'RDB$FILE_NAME = {stored!r}, expected {expected!r}'
