# coding:utf-8
"""
ID:          functional.tablespace.test_gbak_ts_preserve_orig_name
TITLE:       gbak -TS_ORIG must preserve original tablespace names for relation, its index and columns
DESCRIPTION:
    [generated by zcode.ai]
    Restore with -TS_ORIG(INAL_PATHS) recreates each user tablespace at the path that was
    recorded in the backup file. Every object which belonged to that tablespace at backup time
    must be restored to THE SAME tablespace, i.e. RDB$TABLESPACE_NAME of the relation and of
    its index must remain 'TS1', and data must physically be stored in that tablespace again.

    See https://github.com/FirebirdSQL/firebird/commit/b4659fc5597019b1c0472d74486a43d34af08d8f
    ("Fix -ts_orig switch in gbak: the original names must be preserved instead of defaulting
    to PRIMARY", FB 6.0 master, 2026-11-23).

    Before this commit, get_field()/get_index()/get_relation() (src/burp/restore.epp) kept the
    original name ONLY when tablespaceFileMap contained a mapping for it, which is never the
    case when -TS_ORIG is used without -TS/-TS_MAP:
        old: if (str && !str->equals(PRIMARY_TABLESPACE_NAME))
        new: if (!str || !str->equals(PRIMARY_TABLESPACE_NAME))
    As result, on builds with the bug the restored table, its index and its columns silently
    DEFAULTED TO PRIMARY although the tablespace itself was correctly recreated with its
    original name and file, e.g.:
        gstat -t T2 => "Tablespace: PRIMARY"  (instead of TS1), same for index T2_B.

    Checks that are performed by this test:
    1. 'gbak -c' WITHOUT -TS_ORIG and without -TS/-TS_MAP must fail with
       "path to tablespace TS1 is not specified ..." (this works properly on all builds);
    2. 'gbak -c -TS_ORIG' must succeed, and after that:
       - RDB$TABLESPACE_NAME of relation T2 must be 'TS1' (was 'PRIMARY' on builds with the bug);
       - RDB$TABLESPACE_NAME of index T2_B must be 'TS1' (was 'PRIMARY' on builds with the bug);
       - data of T2 must be accessible.
    NB: the same faulty condition exists in get_field() (third affected place of the commit),
    but it can NOT be checked here because in current FB 6.0 there is no DDL that assigns
    a non-primary tablespace to a separate column (RDB$RELATION_FIELDS.RDB$TABLESPACE_NAME
    remains NULL/PRIMARY for all columns of a table which was created with 'TABLESPACE TS1').

NOTES:
    [2026.11.23] pzotov
    Test was generated by AI (ZCode / GLM).

    Confirmed problem on 6.0.0.2504-b7b45c0 (CS): after 'gbak -c -ts_orig' all the metadata
    showed 'PRIMARY' instead of 'TS1' and gstat displayed 'Tablespace: PRIMARY' for both T2
    and T2_B, i.e. data was silently put into PRIMARY tablespace.
    Checked on 6.0.0.2504-b4659fc: all values are 'TS1'.
"""

import re
import pytest
from pathlib import Path
from firebird.qa import *

TS_NAME = 'TS_GBAK_ORIG'
TABLE_NAME = 'T_TS_ORIG'
INDEX_NAME = 'T_TS_ORIG_B'

expected_restore_without_switches = \
    f'gbak: ERROR:path to tablespace {TS_NAME} is not specified (original path: "<ts_file>")'

# Single-row query whose list-mode output contains all the checked facts
expected_stdout = f"""
    REL_TS                          {TS_NAME}
    IDX_TS                          {TS_NAME}
    ROWS_CNT                        100
"""

db = db_factory()
substitutions = [('[ \t]+', ' ')]
act = isql_act('db', substitutions = substitutions)

@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, tmp_path: Path):

    ts_file = tmp_path / 'ts_gbak_orig.dat'
    fbk_file = tmp_path / 'ts_gbak_orig.fbk'
    restored_file = tmp_path / 'ts_gbak_orig_restored.fdb'

    # dsn for the restored database = same host part as act.db.dsn has
    # NB: split(':', 1) because the path part itself contains ':' of the drive letter
    restored_dsn = act.db.dsn.split(':', 1)[0] + ':' + str(restored_file)

    act.isql(switches=['-q'], input=f"""
        create tablespace {TS_NAME} file '{ts_file}';
        commit;
        create table {TABLE_NAME} (id int not null, b varchar(100)) tablespace {TS_NAME};
        commit;
        insert into {TABLE_NAME} select row_number() over(), rpad('x', 50) from rdb$types rows 100;
        commit;
        create index {INDEX_NAME} on {TABLE_NAME}(b);
        commit;
    """)
    assert act.clean_stdout == act.clean_expected_stdout

    act.gbak(switches=['-b', act.db.dsn, str(fbk_file)], combine_output=True)
    assert act.return_code == 0
    act.reset()

    # ------------------------------------------------------------------
    # check #1: restore WITHOUT any -TS* switch must fail with msg 438
    # ------------------------------------------------------------------
    act.gbak(switches=['-c', str(fbk_file), str(restored_file)], combine_output=True)
    assert act.return_code != 0

    import re as _re
    err_lines = [ln for ln in act.stdout.splitlines() if 'ERROR' in ln]
    err_lines = [ re.sub(r'\(original path: ".*"\)', '(original path: "<ts_file>")', ' '.join(ln.split())) for ln in err_lines ]
    assert err_lines == [ ' '.join(expected_restore_without_switches.split()) ], \
        f'Unexpected gbak output:\n{act.stdout}'
    act.reset()

    # ------------------------------------------------------------------
    # check #2: restore WITH -TS_ORIG.
    # The tablespace file must be recreated at its original location,
    # so remove the old one first. Also remove the stub which the failed
    # restore of the check #1 may leave on disk.
    # ------------------------------------------------------------------
    if ts_file.exists():
        ts_file.unlink()
    if restored_file.exists():
        restored_file.unlink()

    act.gbak(switches=['-c', '-ts_orig', str(fbk_file), str(restored_dsn)], combine_output=True)
    assert act.return_code == 0, f'gbak -c -ts_orig failed:\n{act.stdout}\n{act.stderr}'
    act.reset()

    # check that the tablespace file really was recreated at its original path
    assert ts_file.exists(), f'-ts_orig did not recreate tablespace file {ts_file}'

    # ------------------------------------------------------------------
    # check #3: metadata of restored database must keep original names
    # NB: connect_db = False, otherwise isql first implicitly connects to the
    # primary test database and 'Rolling back work.' appears in stderr at exit.
    # ------------------------------------------------------------------
    act.isql(switches=['-q'], connect_db=False, input=f"""
        connect '{restored_dsn}' user '{act.db.user}' password '{act.db.password}';
        set list on;
        select
            (select r.rdb$tablespace_name from rdb$relations r
              where r.rdb$relation_name = '{TABLE_NAME.upper()}') as rel_ts,
            (select i.rdb$tablespace_name from rdb$indices i
              where i.rdb$index_name = '{INDEX_NAME.upper()}') as idx_ts,
            (select count(*) from {TABLE_NAME}) as rows_cnt
            from rdb$database;
            exit;
    """)
    act.expected_stdout = expected_stdout
    assert act.clean_stdout == act.clean_expected_stdout, \
        f'Unexpected metadata after -ts_orig restore:\n{act.stdout}'
