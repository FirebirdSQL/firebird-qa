db = db_factory()
substitutions = [ ('[ \t]+', ' ') ]
act = isql_act('db', substitutions = substitutions)

# Encoding used by the OS for its part of I/O error messages. NOTE:
# locale.getpreferredencoding() can return 'utf-8' (Python UTF-8 mode), so
# the real ANSI code page is queried instead.
if platform.system() == 'Windows':
    os_encoding = 'cp' + str(ctypes.windll.kernel32.GetACP())
else:
    os_encoding = locale.getpreferredencoding(False)

