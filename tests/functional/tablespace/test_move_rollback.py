@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, tmp_path: Path):

    ts_name = 'TS1'     # name of tablespace in DB.
    t_name = 'T1'       # name of table under test.
    idx_name = 'IDX1'   # name of index under test.

    # Random names of files that will be used for storage TS data:
    rnd_name = 'ts_rb_' + generate_random_string(20)
    ts_file = tmp_path / rnd_name

    rnd_name_renamed = 'ts_rb_renamed_' + generate_random_string(20)
    ts_file_renamed = tmp_path / rnd_name_renamed

    # +++++++++++++++++++++++++++++++++ check #1 +++++++++++++++++++++++++++++++++
    # create tablespace, table with 10000 rows and index on it
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    init_sql = f"""
        set bail on;
        set autoterm on;
        create tablespace {ts_name} file '{ts_file}';
        commit;

        create table {t_name.lower()}(id int);
        commit;

        execute block as
            declare variable i int = 0;
        begin
            while (i < 10000) do
            begin
                i = i + 1;
                insert into {t_name.lower()} values (:i);
            end
        end;
        commit;

        create index {idx_name.lower()} on {t_name.lower()} (id);
        commit;
    """
    expected_stdout = ''
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=init_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    def rename_ts_file(do_rename: bool):
        if do_rename:
            os.rename(ts_file, ts_file_renamed)
        else:
            os.rename(ts_file_renamed, ts_file)

    # +++++++++++++++++++++++++++++++++ check #2 +++++++++++++++++++++++++++++++++
    # part 1: rollback of ALTER TABLE SET TABLESPACE.
    # The '-n' switch (autoddl off) is ESSENTIAL here: with autoddl ON isql
    # commits DDL statements immediately (even inside an explicit
    # transaction), so ROLLBACK would not undo the move.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"""
        alter table {t_name.lower()} set tablespace {ts_name};
        rollback;
    """
    expected_stdout = ''
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q', '-n'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # metadata still shows the ORIGINAL tablespace (PRIMARY):
    test_sql = f"""
        set bail on;
        set list on;
        select rdb$tablespace_name as ts_name
        from rdb$relations
        where rdb$relation_name = upper('{t_name}');
    """
    expected_stdout = "TS_NAME PRIMARY"
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # all rows must be accessible:
    test_sql = f"""
        set bail on;
        set list on;
        select count(*) as cnt from {t_name.lower()};
    """
    expected_stdout = "CNT 10000"
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # +++++++++++++++++++++++++++++++++ check #3 +++++++++++++++++++++++++++++++++
    # part 1 (continued): data must NOT reside in TS1: rename its file away
    # and read the table again (this proves that newly allocated pages were
    # freed during the rollback).
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    rename_ts_file(do_rename = True)
    test_sql = f"""
        set bail on;
        set list on;
        select count(*) as cnt from {t_name.lower()};
    """
    expected_stdout = "CNT 10000"
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()
    rename_ts_file(do_rename = False)

    # +++++++++++++++++++++++++++++++++ check #4 +++++++++++++++++++++++++++++++++
    # part 2: rollback of ALTER INDEX SET TABLESPACE.
    # Metadata must show the ORIGINAL tablespace (PRIMARY).
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"""
        alter index {idx_name.lower()} set tablespace {ts_name};
        rollback;
    """
    expected_stdout = ''
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q', '-n'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    test_sql = f"""
        set bail on;
        set list on;
        select rdb$tablespace_name as ts_name
        from rdb$indices
        where rdb$index_name = upper('{idx_name}');
    """
    expected_stdout = "TS_NAME PRIMARY"
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # +++++++++++++++++++++++++++++++++ check #5 +++++++++++++++++++++++++++++++++
    # part 2 (continued): data must still be correct after the index tree
    # was restored.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"""
        set bail on;
        set list on;
        select * from {t_name.lower()} where id = 9999;
    """
    expected_stdout = "ID 9999"
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # +++++++++++++++++++++++++++++++++ check #6 +++++++++++++++++++++++++++++++++
    # KNOWN ENGINE PROBLEM, see docstring: explicit PLAN usage of the
    # restored index is refused after the rollback. This check PINS the
    # currently observed (buggy!) behavior.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"""
        select count(*) as cnt from {t_name.lower()} where id > 9000 plan ({t_name.lower()} index ({idx_name.lower()}));
    """
    expected_stdout = f"""
        Statement failed, SQLSTATE = 42000
        index "PUBLIC"."{idx_name.upper()}" cannot be used in the specified plan
    """
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # +++++++++++++++++++++++++++++++++ check #7 +++++++++++++++++++++++++++++++++
    # part 3: positive control -- COMMITTED move: after the tablespace file
    # is renamed away, access must fail with an I/O error (data were really
    # moved into the committed tablespace).
    # NOTE 1: BEFORE renaming the file we shut the database down and bring
    # it back online after that. Otherwise the rename would NOT guarantee
    # the desired effect: the server can keep an open handle to the TS file
    # (e.g. its async write thread) and continue to serve data through that
    # handle even after the file has been renamed (flaky behavior observed
    # in practice).
    # NOTE 2: io_enc is required because the OS provided part of I/O error
    # messages is issued in the ANSI code page of the OS (non-English on
    # non-English Windows), and we assert only its language-independent part.
    # ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
    test_sql = f"""
        alter table {t_name.lower()} set tablespace {ts_name};
        commit;
    """
    expected_stdout = ''
    act.expected_stdout = expected_stdout
    act.isql(switches = ['-q'], input=test_sql, combine_output = True)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # Shut the DB down: this forces the server to close ALL handles to ALL
    # its files, including the tablespace file.
    act.gfix(switches = ['-shut', 'full', '-force', '0', str(act.db.db_path)])
    act.reset()

    rename_ts_file(do_rename = True)

    act.gfix(switches = ['-online', 'normal', str(act.db.db_path)])
    act.reset()

    test_sql = f"""
        set list on;
        select count(*) as cnt from {t_name.lower()};
    """
    act.isql(switches = ['-q'], input=test_sql, combine_output = True, io_enc = os_encoding)
    assert 'I/O error' in act.clean_stdout
    assert 'CNT' not in act.clean_stdout
