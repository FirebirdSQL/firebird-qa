"""
ID:           functional.tablespace.test_alter_index_set_ts_deadlock
TITLE:        Fix deadlock in ALTER INDEX ... SET TABLESPACE for non-first indexes
DESCRIPTION:
    [generated by zcode.ai]
    BTR_copy_index() (which performs actual copying of index pages when 'ALTER INDEX ... SET TABLESPACE' commits) passed MetaId
    of the processed index into checkIrtRepeat() as its 'skipInProgress' argument (bool). Because of this, for any NON-first
    index (MetaId > 0) checkIrtRepeat() behaved as if it was called during the "skip in progress" processing and did NOT release
    the latch of the fetched index root page even when it decided that index descriptor requires modification (returned true).
    Subsequent call of BTR_fetch_root_for_update() then tried to fetch the same page with LCK_write latch which was ALREADY held
    by the same thread - engine entered infinite latch wait ("deadlock" in sense of self-blocked thread).

    The most easy reproducible scenario:
    1. some table has at least two indexes (so that altered index has MetaId > 0);
    2. ALTER INDEX <idx> SET TABLESPACE <ts1> is successfully committed. Its slot in the index root page remains in irt_migrate
       state (with committed transaction number) until this state is lazily resolved by some scan of index descriptors;
    3. immediately after that ALTER INDEX <idx> SET TABLESPACE <ts2> is issued.
       BTR_copy_index() now detects irt_migrate with committed transaction and, for non-first index, deadlocks as described
       above.

    Scenario is performed in CHILD python process (see NOTES), which:
    1. creates its own (throwaway) database in tmp dir, two tablespaces, table with PK (first index) and secondary index IDX_B
       (non-first, MetaId = 1), and populates it with two rows;
    2. executes ALTER INDEX IDX_B SET TABLESPACE TS1 + commit (this succeeds both before and after the fix);
    3. executes ALTER INDEX IDX_B SET TABLESPACE TS2 + commit;
    4. selects count(*) from the migrated table.

    * BEFORE the fix: child process HANGS at step 3 and is killed by timeout; its log shows no 'second ALTER ...: OK' marker.
    * AFTER the fix: all steps complete, child exits with count = 2.

NOTES:
    [21.11.2026] pzotov
    Test was generated by zcode.ai.
    FIX_COMMIT:   https://github.com/FirebirdSQL/firebird/commit/2da5432096d02ae4747fc8f70a2d7d15857e1337
    1. WHY CHILD PROCESS: on bugged build the child gets stuck inside the engine call (infinite latch wait). Child performs all
       the work and is killed by subprocess timeout, so pytest process remains healthy (see similar notes in
       functional/metacache/test_3dc55fb.py).
    2. ON BUGGED BUILD THE THROWAWAY DATABASE REMAINS LOCKED: after the child is killed, the worker thread which served its
       attachment stays in infinite latch wait (the thread lives inside the server process), so files of this throwaway DB and
       its tablespaces can not be deleted. Test makes only best-effort attempt to remove them and does NOT assert on the cleanup
       outcome. These leftovers accumulate in the pytest tmp dir per each test run against bugged build.
    3. The fix itself is mode-independent (src/jrd/btr.cpp, BTR_copy_index()), so the same clean outcome is expected on fixed
       Classic/SuperClassic builds.
    4. Checked with Python 3.11.8 / firebird-driver, localhost, TCP.
    Confirmed bug on 6.0.0.2496-f0accd6 (build without fix).
    Checked on 6.0.0.2500-30783bf (build with fix).
"""

import os
import sys
import subprocess
from pathlib import Path

import pytest
from firebird.qa import *

db = db_factory(do_not_create = True, do_not_drop = True)
act = python_act('db', substitutions=[('[ \t]+', ' ')])

tmp_child_py  = temp_file('gh_ts_worker.py')
tmp_child_log = temp_file('gh_ts_worker.log')

# Max time that we allow to the child process be in 'running state':
MAX_CHILD_TIMEOUT = 60

CHILD_SOURCE = r'''
import sys
import os
import firebird.driver as fbd
from firebird.driver import create_database

# argv: 1=host 2=port 3=db_path 4=ts1_file 5=ts2_file 6=user 7=password 8=fbclient_library
host, port, dbpath, ts1, ts2, usr, pwd, lib = sys.argv[1:9]

srv_nm, db_nm = 'ts2da_srv', 'ts2da_db'
fbd.driver_config.register_server(srv_nm, f"""
[{srv_nm}]
host = {host}
port = {port}
fb_client_library = {lib}
""")
fbd.driver_config.register_database(db_nm, f"""
[{db_nm}]
server = {srv_nm}
database = {dbpath}
""")

def say(msg):
    # flush after each line: child may be killed at any point
    print(msg, flush=True)

con = create_database(db_nm, user=usr, password=pwd)
say('database created and attached')

for sql in (
    f"CREATE TABLESPACE TS1 FILE '{ts1}'",
    f"CREATE TABLESPACE TS2 FILE '{ts2}'",
):
    con.execute_immediate(sql)
con.commit()
say('tablespaces TS1 and TS2 created')

# PK will take index slot 0 (FIRST index), IDX_B gets slot 1 (NON-FIRST index):
for sql in (
    'CREATE TABLE T1(ID INT NOT NULL, B INT)',
    'ALTER TABLE T1 ADD CONSTRAINT PK_T1 PRIMARY KEY(ID)',
    'CREATE INDEX IDX_B ON T1(B)',
):
    con.execute_immediate(sql)
con.commit()
say('table with PK (first index) and secondary index IDX_B created')

for sql in (
    'INSERT INTO T1 VALUES(1, 100)',
    'INSERT INTO T1 VALUES(2, 200)',
):
    con.execute_immediate(sql)
con.commit()
say('two rows inserted')

# 1st migration of NON-FIRST index succeeds both before and after the fix.
# Its slot remains in irt_migrate state after this commit:
con.execute_immediate('ALTER INDEX IDX_B SET TABLESPACE TS1')
con.commit()
say('first ALTER INDEX IDX_B SET TABLESPACE TS1: OK')

# 2nd migration: on bugged build engine self-deadlocks here
# (infinite latch wait on index root page):
con.execute_immediate('ALTER INDEX IDX_B SET TABLESPACE TS2')
con.commit()
say('second ALTER INDEX IDX_B SET TABLESPACE TS2: OK')

rows = list(con.cursor().execute('SELECT COUNT(*) FROM T1'))
say('select from migrated table: OK, rows=' + str(rows))

con.close()
os._exit(0)
'''

@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, tmp_path: Path, tmp_child_py: Path, tmp_child_log: Path, capsys):

    throwaway_db = tmp_path / 'ts_2da54320_throwaway.fdb'
    ts1_file = tmp_path / 'ts_2da54320_a.dat'
    ts2_file = tmp_path / 'ts_2da54320_b.dat'

    tmp_child_py.write_text(CHILD_SOURCE, encoding='utf-8')
    tmp_child_log.unlink(missing_ok = True)

    cmd_child = [
        sys.executable, '-X', 'utf8', str(tmp_child_py),
        str(act.vars['host']), str(act.vars['port']),
        str(throwaway_db), str(ts1_file), str(ts2_file),
        act.db.user, act.db.password, act.vars['fbclient']
    ]
    try:
        with open(tmp_child_log, 'w') as f:
            # note: on bugged builds this child HANGS in ALTER INDEX ... SET TABLESPACE
            p = subprocess.run(cmd_child, stdout = f, stderr = subprocess.STDOUT,
                               timeout = MAX_CHILD_TIMEOUT)
            print(f'child returncode: {p.returncode}')
    except subprocess.TimeoutExpired as e:
        print(f'{e.__class__=}')
        print(e.__str__())

    if tmp_child_log.is_file():
        with open(tmp_child_log, 'r') as f:
            for line in f:
                print(line.rstrip())

    act.expected_stdout = f"""
        child returncode: 0
        database created and attached
        tablespaces TS1 and TS2 created
        table with PK (first index) and secondary index IDX_B created
        two rows inserted
        first ALTER INDEX IDX_B SET TABLESPACE TS1: OK
        second ALTER INDEX IDX_B SET TABLESPACE TS2: OK
        select from migrated table: OK, rows=[(2,)]
    """

    act.stdout = capsys.readouterr().out
    assert act.clean_stdout == act.clean_expected_stdout

    # Best-effort cleanup of the throwaway DB files. On bugged builds these files
    # are locked by the hung server worker and can NOT be removed - this is NOT
    # an assertion failure, see NOTES.
    for f in (throwaway_db, ts1_file, ts2_file):
        try:
            os.remove(f)
        except OSError:
            pass
