import re
import pytest
from pathlib import Path
from firebird.qa import *

TS_NAME = 'TS_EXIST'
TABLE_NAME = 'T_EXIST'

db = db_factory()
act = python_act('db')

ALREADY_EXISTS_PATTERN = re.compile(r'Tablespace file\s+"([^"]+)"\s+already exists', re.I)


def ts_file_fingerprint(path: Path) -> tuple:
    """Size and mtime of the file, to be compared before/after failed restore."""
    st = path.stat()
    return (st.st_size, st.st_mtime_ns)


def assert_already_exists_error(act: Action, out_text: str, expected_path: Path) -> None:
    """Check that gbak output contains the 'Tablespace file ... already exists' message
    with the resolved path, ignoring letter case and separator kind."""
    assert act.return_code != 0, f'gbak -c unexpectedly succeeded:\n{out_text}'

    msgs = ALREADY_EXISTS_PATTERN.findall(out_text)
    assert msgs, \
        f'No "Tablespace file ... already exists" message found (old builds emit raw ' \
        f'I/O error instead):\n{out_text}'

    norm = lambda s: str(s).replace('/', '\\').lower()
    reported = next((m for m in msgs if norm(m) == norm(expected_path)), None)
    assert reported is not None, \
        f'Error message reports {msgs!r}, expected path {str(expected_path)!r}:\n{out_text}'


@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, tmp_path: Path):

    # dsn for a database file = same host part as act.db.dsn has
    # NB: split(':', 1) because the path part itself contains ':' of the drive letter
    def make_dsn(f: Path) -> str:
        return act.db.dsn.split(':', 1)[0] + ':' + str(f)

    # ############### part 1: single tablespace, -TS / -TS_ORIG / relative name ###############

    ts_file = tmp_path / 'ts_exist.dat'
    fbk_file = tmp_path / 'ts_exist.fbk'
    restored_file = tmp_path / 'ts_exist_restored.fdb'
    restored_dsn = make_dsn(restored_file)

    act.isql(switches=['-q'], input=f"""
        create tablespace {TS_NAME} file '{ts_file}';
        commit;
        create table {TABLE_NAME} (id int) tablespace {TS_NAME};
        commit;
        insert into {TABLE_NAME} select row_number() over() from rdb$types rows 100;
        commit;
    """)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    act.gbak(switches=['-b', act.db.dsn, str(fbk_file)], combine_output=True)
    assert act.return_code == 0, f'gbak -b failed:\n{act.stdout}\n{act.stderr}'
    act.reset()

    # ### negative case: file of TS1 already exists (it was NOT deleted after backup) ###
    before = ts_file_fingerprint(ts_file)

    # NB: io_enc='latin-1' decodes ANY byte without error: on bugged builds gbak prints
    # the OS-dependent message about file existence in the raw ANSI codepage, which is
    # not UTF-8 and would cause UnicodeDecodeError before our assertions could run.
    # All messages that are checked here are pure ASCII, so latin-1 is sufficient.
    act.gbak(switches=['-c', str(fbk_file), restored_dsn, '-TS', TS_NAME, str(ts_file)],
             combine_output=True, io_enc='latin-1')
    assert_already_exists_error(act, act.stdout, ts_file)

    # pre-existing file must not be touched by the failed restore
    assert ts_file_fingerprint(ts_file) == before, \
        f'File {ts_file} was modified by the failed restore'
    # remove the partially restored db: it would block the next restore attempt
    restored_file.unlink(missing_ok=True)
    act.reset()

    # ### negative case with -TS_ORIG: original file still exists on its recorded path ###
    act.gbak(switches=['-c', str(fbk_file), restored_dsn, '-TS_ORIG'],
             combine_output=True, io_enc='latin-1')
    assert_already_exists_error(act, act.stdout, ts_file)
    assert ts_file_fingerprint(ts_file) == before, \
        f'File {ts_file} was modified by the failed restore'
    restored_file.unlink(missing_ok=True)
    act.reset()

    # ### negative case with RELATIVE mapping name: message must show the RESOLVED path ###
    sub_dir = tmp_path / 'sub'
    sub_dir.mkdir(exist_ok=True)
    sub_file = sub_dir / 'ts_rel.dat'
    sub_file.write_bytes(b'placeholder, must not be overwritten by restore')

    act.gbak(switches=['-c', str(fbk_file), restored_dsn, '-TS', TS_NAME, 'sub/ts_rel.dat'],
             combine_output=True, io_enc='latin-1')
    assert_already_exists_error(act, act.stdout, sub_file)

    assert sub_file.read_bytes() == b'placeholder, must not be overwritten by restore', \
        f'File {sub_file} was overwritten by the failed restore'
    restored_file.unlink(missing_ok=True)
    act.reset()

    # ### control: restore to a NON-existing file must succeed ###
    ts_file_ctl = tmp_path / 'ts_exist_ctl.dat'
    restored_ctl = tmp_path / 'ts_exist_restored_ctl.fdb'
    restored_ctl_dsn = make_dsn(restored_ctl)

    act.gbak(switches=['-c', str(fbk_file), restored_ctl_dsn, '-TS', TS_NAME, str(ts_file_ctl)],
             combine_output=True)
    assert act.return_code == 0, \
        f'Control restore to non-existing tablespace file failed:\n{act.stdout}'
    act.reset()

    act.isql(switches=['-q'], connect_db=False, input=f"""
        connect '{restored_ctl_dsn}' user '{act.db.user}' password '{act.db.password}';
        set list on;
        select
            (select count(*) from {TABLE_NAME}) as rows_cnt,
            (select x.rdb$file_name from rdb$tablespaces x where x.rdb$system_flag <> 1) as ts_file
            from rdb$database;
            exit;
    """)
    # exact (case/slash-insensitive) check of the stored file name: the value
    # must be extracted BEFORE act.stdout is masked for the comparison below
    stored_names = re.findall(r'TS_FILE\s+(\S.*)', act.stdout, flags=re.I)

    act.stdout = re.sub(r'TS_FILE\s+\S.*', 'TS_FILE <ts_file>', act.stdout, flags=re.I)
    act.expected_stdout = f"""
        ROWS_CNT                        100
        TS_FILE <ts_file>
    """
    assert act.clean_stdout == act.clean_expected_stdout, \
        f'Unexpected content of restored database:\n{act.stdout}'

    assert stored_names, f'RDB$FILE_NAME not found in output:\n{act.stdout}'
    stored = stored_names[0].strip().replace('/', '\\').lower()
    expected = str(ts_file_ctl).replace('/', '\\').lower()
    assert stored == expected, f'RDB$FILE_NAME = {stored!r}, expected {expected!r}'
    act.reset()

    # ############### part 2: fail-fast, no side effect for the second tablespace ###############

    # drop objects of the first part: the backup made below must contain ONLY TSA and TSB
    act.isql(switches=['-q'], input=f"""
        drop table {TABLE_NAME};
        drop tablespace {TS_NAME};
        commit;
    """)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    ts_file_a = tmp_path / 'ts_fail_fast_a.dat'
    ts_file_b = tmp_path / 'ts_fail_fast_b.dat'
    ts_mapped_b = tmp_path / 'ts_fail_fast_b_mapped.dat'
    fbk_file = tmp_path / 'ts_fail_fast.fbk'
    restored_file = tmp_path / 'ts_fail_fast_restored.fdb'
    restored_dsn = make_dsn(restored_file)

    act.isql(switches=['-q'], input=f"""
        create tablespace TSA file '{ts_file_a}';
        create tablespace TSB file '{ts_file_b}';
        commit;
        create table TA (id int) tablespace TSA;
        create table TB (id int) tablespace TSB;
        commit;
        insert into TA values(1);
        insert into TB values(2);
        commit;
    """)
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    act.gbak(switches=['-b', act.db.dsn, str(fbk_file)], combine_output=True)
    assert act.return_code == 0, f'gbak -b failed:\n{act.stdout}\n{act.stderr}'
    act.reset()

    # TSA is restored to its ORIGINAL file, which still exists;
    # TSB is restored to a fresh file that does not exist yet
    assert ts_file_a.exists() and not ts_mapped_b.exists()

    act.gbak(switches=['-c', str(fbk_file), restored_dsn,
                       '-TS', 'TSA', str(ts_file_a),
                       '-TS', 'TSB', str(ts_mapped_b)],
             combine_output=True, io_enc='latin-1')

    assert_already_exists_error(act, act.stdout, ts_file_a)

    # fail-fast: the restore must abort at the FIRST failed tablespace and must NOT
    # create the file which was mapped for the second one.
    # (old builds printed the I/O error, went on to process TSB, created its file
    # on disk, and only then aborted)
    assert not ts_mapped_b.exists(), \
        f'File of the second tablespace {ts_mapped_b} was created although the restore ' \
        f'aborted because of the first tablespace:\n{act.stdout}'
    act.reset()
