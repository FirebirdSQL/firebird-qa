def sim_escape(s):
    # escape ONLY characters that are allowed to be escaped, see docstring
    return ''.join('\\' + ch if ch in SIMILAR_ESCAPABLE else ch for ch in s)


def days_in_month(y, m):
    if m == 2:
        return 29 if (y % 4 == 0 and (y % 100 != 0 or y % 400 == 0)) else 28
    return (31,28,31,30,31,30,31,31,30,31,30,31)[m-1]


def gen_date_parts(rnd):
    r = rnd.random()
    if r < 0.04:
        return (1, 1, 1)
    if r < 0.08:
        return (9999, 12, 31)
    if r < 0.12:
        return (2024, 2, 29)
    y = rnd.randint(1, 9999) if rnd.random() < 0.1 else rnd.randint(1900, 2100)
    m = rnd.randint(1, 12)
    d = rnd.randint(1, days_in_month(y, m))
    return (y, m, d)


def date_lit(rnd, y, m, d):
    # Random format of literal, see NOTE-1.2 of the request.
    # 4-digits years are used for all forms except when y surely falls into
    # FB window for 2-digit years (2000..2049).
    r = rnd.random()
    if r < 0.6:
        return f"date '{y:04d}-{m:02d}-{d:02d}'"
    elif r < 0.7:
        return f"date '{d:02d}.{m:02d}.{y:04d}'"
    elif r < 0.8:
        return f"date '{d:02d}-{MONTH_ABBR[m-1]}-{y:04d}'"
    elif r < 0.9 and 2000 <= y <= 2049:
        return f"date '{m}/{d}/{y % 100:02d}'"
    else:
        return f"date '{m} {d} {y:04d}'"


def gen_time_parts(rnd):
    # returns (hours, minutes, seconds, fraction_in_1_10000_units)
    r = rnd.random()
    if r < 0.04:
        return (0, 0, 0, 0)
    if r < 0.08:
        return (23, 59, 59, 9999)
    h = rnd.randint(0, 23)
    mi = rnd.randint(0, 59)
    s = rnd.randint(0, 59)
    frac = 0 if rnd.random() < 0.5 else rnd.randint(0, 9999)
    return (h, mi, s, frac)


def time_text(rnd, h, mi, s, frac):
    # Random format of time literal, see NOTE-1.3 of the request:
    # some parts may be omitted (leading zeroes or entire seconds).
    r = rnd.random()
    if r < 0.6:
        return f'{h:02d}:{mi:02d}:{s:02d}.{frac:04d}'
    elif frac == 0 and r < 0.75:
        return f'{h}:{mi}:{s}'
    elif s == 0 and frac == 0 and r < 0.85:
        return f'{h}:{mi}'
    elif s == 0 and frac % 10 == 0:
        return f'{h}:{mi}.{frac // 10}'
    else:
        return f'{h:02d}:{mi:02d}:{s:02d}.{frac:04d}'


def gen_tz_text(rnd, force_utc=False):
    if force_utc:
        return '+00:00'
    if rnd.random() < 0.5:
        h = rnd.randint(-14, 14)
        mm = 0 if abs(h) == 14 else rnd.choice((0, 0, 15, 30, 45))
        return f'{h:+03d}:{mm:02d}'
    return rnd.choice(TZ_REGIONS)


def gen_dig(rnd, n, lead_nz=True):
    first = rnd.choice('123456789') if lead_nz else rnd.choice('0123456789')
    return first + ''.join(rnd.choice('0123456789') for _ in range(n - 1))


def gen_lit(rnd, col):
    """Returns SQL literal (or expression) for INSERT into given column."""
    if col == 'dt':
        y, m, d = gen_date_parts(rnd)
        return date_lit(rnd, y, m, d)

    elif col == 'tm':
        h, mi, s, frac = gen_time_parts(rnd)
        return f"time '{time_text(rnd, h, mi, s, frac)}'"

    elif col == 'ts':
        y, m, d = gen_date_parts(rnd)
        h, mi, s, frac = gen_time_parts(rnd)
        return f"timestamp '{date_lit(rnd, y, m, d)[6:-1]} {time_text(rnd, h, mi, s, frac)}'"

    elif col == 'tmtz':
        h, mi, s, frac = gen_time_parts(rnd)
        return f"time '{time_text(rnd, h, mi, s, frac)} {gen_tz_text(rnd)}'"

    elif col == 'tstz':
        y, m, d = gen_date_parts(rnd)
        h, mi, s, frac = gen_time_parts(rnd)
        # timestamps with extreme dates may overflow if tz offset moves them
        # out of allowed range, e.g. 0001-01-01 in Asia/Tokyo or 9999-12-31 -14:00:
        tz = gen_tz_text(rnd, force_utc = y in (1, 9999))
        return f"timestamp '{date_lit(rnd, y, m, d)[6:-1]} {time_text(rnd, h, mi, s, frac)} {tz}'"

    elif col == 'flt':
        r = rnd.random()
        if r < 0.03:
            return "cast('1.17549435e-38' as float)"
        elif r < 0.06:
            return "cast('3.4028234e38' as float)"
        elif r < 0.09:
            return "cast('1e-45' as float)"
        elif r < 0.12:
            return "cast('0.0' as float)"
        sign = '-' if rnd.random() < 0.5 else ''
        mant = rnd.choice('123456789') + '.' + gen_dig(rnd, rnd.randint(1, 7), lead_nz = False)
        exp = rnd.randint(-30, 30)
        return f"cast('{sign}{mant}e{exp}' as float)"

    elif col == 'dbl':
        r = rnd.random()
        if r < 0.03:
            return "cast('1.7976931348623157e308' as double precision)"
        elif r < 0.06:
            return "cast('1e-308' as double precision)"
        elif r < 0.09:
            return "cast('0.0' as double precision)"
        sign = '-' if rnd.random() < 0.5 else ''
        mant = rnd.choice('123456789') + '.' + gen_dig(rnd, rnd.randint(1, 15), lead_nz = False)
        exp = rnd.randint(-100, 100)
        return f"cast('{sign}{mant}e{exp}' as double precision)"

    elif col in ('df16', 'df34'):
        # DECFLOAT(16): precision 16, adjusted exponent range [-383, +384]
        # DECFLOAT(34): precision 34, adjusted exponent range [-6143, +6144]
        prec = 16 if col == 'df16' else 34
        min_adj = -383 if col == 'df16' else -6143
        max_adj = 384 if col == 'df16' else 6144
        r = rnd.random()
        if r < 0.03:
            lit = '9.' + '9' * (prec - 1) + f'e{max_adj}'
        elif r < 0.06:
            lit = '-9.' + '9' * (prec - 1) + f'e{max_adj}'
        elif r < 0.09:
            lit = f'1e{min_adj}'
        elif r < 0.12:
            lit = '0e0'
        else:
            sign = '-' if rnd.random() < 0.5 else ''
            n_int = rnd.randint(1, prec)
            n_frac = rnd.randint(0, prec - n_int)
            mant = gen_dig(rnd, n_int) + ('.' + gen_dig(rnd, n_frac, lead_nz = False) if n_frac else '')
            # adjusted exponent (exp + digits before point - 1) must stay within
            # [min_adj, max_adj], otherwise "Decimal float overflow" raises,
            # e.g. -204709521.45E382 => adjusted exponent E+390:
            exp = rnd.randint(min_adj - n_int + 1, max_adj - n_int + 1)
            lit = f'{sign}{mant}E{exp}'
        return f"cast('{lit}' as decfloat({prec}))"

    elif col == 'i128':
        r = rnd.random()
        if r < 0.03:
            return "cast('0' as int128)"
        elif r < 0.06:
            return "cast('" + '9' * 38 + "' as int128)"
        elif r < 0.09:
            return "cast('-170141183460469231731687303715884105728' as int128)"
        elif r < 0.12:
            return "cast('170141183460469231731687303715884105727' as int128)"
        sign = '-' if rnd.random() < 0.5 else ''
        return f"cast('{sign}{gen_dig(rnd, rnd.randint(1, 30))}' as int128)"

    elif col == 'bl':
        return rnd.choice(('true', 'false'))


# --------- builders of alternative literals for "must return 0" checks ---------
# All of them produce string which is VALID literal of the SAME value as the
# canonical text represents, but written differently. Before the fix the engine
# converted such pattern to operand type and back to text => query returned 1.

def date_alts(y, m, d):
    res = [
        f'{d:02d}.{m:02d}.{y:04d}',
        f'{d}-{MONTH_ABBR[m-1]}-{y}',
        f'{m}/{d}/{y}',
        f'{m} {d} {y}',
        f'{MONTH_ABBR[m-1]} {d} {y}',
        f'{d}/{MONTH_ABBR[m-1]}/{y}',
    ]
    if 2000 <= y <= 2049:
        yy = y % 100
        res.extend([
            f'{d}.{m}.{yy}',
            f'{d}-{MONTH_ABBR[m-1]}-{yy}',
            f'{m}/{d}/{yy}',
            f'{m} {d} {yy}',
            f'{MONTH_ABBR[m-1]} {d} {yy}',
            f'{d}/{MONTH_ABBR[m-1]}/{yy}',
        ])
    return res


def time_alts(h, mi, s, frac):
    res = [f'{h}:{mi}:{s}']
    if s == 0:
        res.append(f'{h}:{mi}')
        if frac == 0:
            res.append(f'{h}:{mi}.0')
        elif frac % 10 == 0:
            res.append(f'{h}:{mi}.{frac // 10}')
    if frac and frac % 100 == 0:
        res.append(f'{h}:{mi}:{s}.{frac // 100}')
    return res


def zero_alts(col, canon):
    """Candidates of patterns for 'must return 0' checks; guard filters them later."""
    if col in ('flt', 'dbl', 'df16', 'df34', 'i128'):
        res = []
        # leading zero (must be inserted AFTER sign, i.e. '-3.5' => '-03.5'):
        res.append('-0' + canon[1:] if canon.startswith('-') else '0' + canon)
        low = canon.lower()
        if 'e' in low:
            i = low.index('e')
            res.append(canon[:i] + '0' + canon[i:])
        elif '.' in canon:
            res.append(canon + '0')
        return res

    if col == 'bl':
        return [canon.lower()]

    if col == 'dt':
        y, m, d = (int(x) for x in canon.split('-'))
        return date_alts(y, m, d)

    if col == 'tm':
        tp, fr = canon.split('.')
        h, mi, s = (int(x) for x in tp.split(':'))
        return time_alts(h, mi, s, int(fr))

    if col == 'ts':
        dp, tp = canon.split(' ')
        tsec, fr = tp.split('.')
        y, m, d = (int(x) for x in dp.split('-'))
        h, mi, s = (int(x) for x in tsec.split(':'))
        return [f'{da} {ta}' for da in date_alts(y, m, d) for ta in time_alts(h, mi, s, int(fr))]

    if col == 'tmtz':
        tp, tz = canon.split(' ', 1)
        tsec, fr = tp.split('.')
        h, mi, s = (int(x) for x in tsec.split(':'))
        return [f'{ta} {tz}' for ta in time_alts(h, mi, s, int(fr))]

    if col == 'tstz':
        dp, tp, tz = canon.split(' ', 2)
        tsec, fr = tp.split('.')
        y, m, d = (int(x) for x in dp.split('-'))
        h, mi, s = (int(x) for x in tsec.split(':'))
        return [f'{da} {ta} {tz}' for da in date_alts(y, m, d) for ta in time_alts(h, mi, s, int(fr))]


def presence_wheres(col, t):
    """Queries which MUST find the stored row (count = 1), patterns from canonical text."""
    n = len(t)
    a = max(1, n // 4)
    b = n - max(1, n // 4)
    if b <= a:
        b = a
    pre, suf = t[:a], t[b:]
    c = n // 3
    d = min(n, max(c + 1, 2 * n // 3))
    mid = t[c:d] or t
    st = t[:max(1, n // 2)]
    # underscore (ASCII #95), unlike '%', matches EXACTLY ONE character,
    # so pattern has to preserve total length of the canonical text:
    u_pre, u_suf = t[:a], t[a + 1:]
    u_pat = '_' if n == 1 else u_pre + '_' + u_suf
    u_sim_pat = '_' if n == 1 else sim_escape(u_pre) + '_' + sim_escape(u_suf)
    return (
        ('like',          f"{col} like '{pre}%{suf}'"),
        ('containing',    f"{col} containing '{mid}'"),
        ('starting with', f"{col} starting with '{st}'"),
        ('similar to',    f"{col} similar to '{sim_escape(pre)}%{sim_escape(suf)}'{SIMILAR_ESCAPE_CLAUSE}"),
        ('like [underscore]',       f"{col} like '{u_pat}'"),
        ('like [underscore only]',  f"{col} like '{'_' * n}'"),
        ('similar to [underscore]', f"{col} similar to '{u_sim_pat}'{SIMILAR_ESCAPE_CLAUSE}"),
    )


def nonascii_wheres(col, op):
    """Single query with 3 OR-ed parts (2-, 3- and 4-bytes chars); MUST return 0 and not raise."""
    def one_part(ch):
        if op == 'like':
            return f"{col} like '{ch}%'"
        elif op == 'similar to':
            return f"{col} similar to '{ch}%'{SIMILAR_ESCAPE_CLAUSE}"
        else:
            return f"{col} {op} '{ch}'"
    return ' or '.join(one_part(ch) for ch in NONASCII_CHARS)


