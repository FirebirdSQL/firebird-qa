#coding:utf-8
"""
ID:          issue-9017
ISSUE:       https://github.com/FirebirdSQL/firebird/issues/9017
TITLE:       Hard-committed transaction causes false 'update conflicts' on SuperClassic (5.0.3 and 5.0.4)
DESCRIPTION:
    [generated by zcode.ai]
    TIP cache (TPC) stores transaction states and commit numbers in shared memory blocks, one file per block of
    TipCacheBlockSize / sizeof(CommitNumber) transactions (~8180 transactions per block when TipCacheBlockSize = 65536, see
    firebird.conf template).
    Per bug gh-9017 (fixed by PR #9264, commit 2452420), in Classic/SuperClassic the last process that used a TIP cache status
    block UNLINKED its backing file on detach (TipCache::StatusBlockData::clear()), so any NEW attachment silently re-created
    that block ZEROED. Zeroed block means CN_ACTIVE for every transaction stored in it, hence:
        * hard-committed transactions were seen as ACTIVE by new attachments =>
          false "update conflict with concurrent update" / deadlock errors;
        * committed data became invisible for new snapshot attachments (MVCC violation).
    This test reproduces the issue deterministically (scenario originates from PR #9233 discussion, adapted for gh-9017
    symptoms):
        1. test DB is created via ALIAS which is defined in temporary databases.conf with per-database config
           'TipCacheBlockSize = 65536';
        2. persistent attachment A commits row (1, 'original') and stays connected (this keeps the global TPC header alive
           during whole test);
        3. attachment B commits ~11400 autonomous transactions (burst safely crosses the FIRST block boundary, so transactions
           land in TPC block #1), then detaches;
        4. attachment C commits UPDATE of the row -> 'updated_C', then detaches (its transaction also belongs to block #1);
        5. fresh attachment D must see committed 'updated_C' (on buggy build it sees stale 'original' because block #1 was
           re-created zeroed);
        6. fresh attachment E (separate isql process) re-updates the row: must succeed silently (on buggy build it fails with
           "deadlock / update conflicts with concurrent update / concurrent transaction number is <N>" -- the exact error
           that was reported in gh-9017);
        7. fresh attachment F must see 'updated_E'.
    Test asserts CORRECT (fixed) behavior on all steps and runs on any server mode: on Classic and SuperClassic it fails against
    affected builds, on SuperServer it passes trivially (single process keeps TPC blocks alive, they are not unlinked
    while at least one connection persists).
NOTES:
    [16.11.2026] pzotov
    Test was generated by zcode.ai.
    Per-database parameter TipCacheBlockSize is set via temporary replacement of databases.conf (see ConfigManager usage).
    NOTE: DPB-based per-attachment config override ('config' property of driver DatabaseConfig) can NOT be used here:
    over INET such overrides are ignored by the server, so TPC block size would remain its default (4M) and the burst
    would not cross block boundary.

    Confirmed bug on: 6.0.0.2463-2006f08; 5.0.5.1964-8512da6 ; 4.0.8.3341-a2a6cb3
    Checked on: 6.0.0.2463-2452420 ; 5.0.5.1964-947c1c6 ; 4.0.8.3341-a2a6cb3.
"""

import pytest
from firebird.qa import *
from firebird.driver import driver_config, connect, create_database

TPC_ALIAS = 'tmp_gh_9017_tpc'
TPC_BLOCK_SIZE = 65536       # ~8180 transactions per TIP cache block (8 bytes per txn)
BURST_TXNS = 11400           # safely crosses FIRST block boundary, stops inside block #1

db = db_factory(filename = 'gh_9017_tpc.fdb', do_not_create = True)
act = python_act('db')

@pytest.mark.ai
@pytest.mark.disabled_in_forks
@pytest.mark.version('>=4.0')
def test_1(act: Action, store_config: ConfigManager, capsys):

    if act.vars['server-arch'].lower() != 'classic':
        pytest.skip('Applies only to Classic')

    test_db_file = str(act.db.db_path)  # full path: DB was not created by fixture (do_not_create)

    # add alias for the test DB with per-database TipCacheBlockSize to databases.conf;
    # original content will be restored by store_config fixture at teardown.
    # NB: we operate in BYTES mode to preserve the original file content 'as is'
    # (comments in the conf may be non-ASCII):
    tmp_databases_conf = act.db.db_path.parent / 'tmp_gh_9017_databases.conf'
    old_conf = (act.vars['home-dir'] / 'databases.conf').read_bytes()
    tmp_databases_conf.write_bytes(old_conf + f"""
{TPC_ALIAS} = {test_db_file}
{{
    TipCacheBlockSize = {TPC_BLOCK_SIZE}
}}
""".encode('ascii'))
    store_config.replace('databases.conf', tmp_databases_conf)

    srv_cfg = driver_config.register_server(name = 'srv_cfg_gh_9017', config = '')
    srv_cfg.host.value = act.vars['host']
    srv_cfg.port.value = act.vars['port']

    db_cfg_name = 'db_cfg_gh_9017'
    db_cfg = driver_config.register_database(name = db_cfg_name)
    db_cfg.server.value = srv_cfg.name
    db_cfg.database.value = TPC_ALIAS
    db_cfg.user.value = act.db.user
    db_cfg.password.value = act.db.password

    # DSN for explicit connect from isql script (command line tools require full dsn with port)
    port = act.vars['port']
    alias_dsn = f"{act.vars['host']}/{port}:{TPC_ALIAS}" if port else f"{act.vars['host']}:{TPC_ALIAS}"

    def get_conn():
        return connect(db_cfg_name, user = act.db.user, password = act.db.password)

    step_descs = []
    step_results = []
    def report(step_desc, ok):
        step_descs.append(step_desc)
        step_results.append(ok)
        print(f'{step_desc}: {"OK" if ok else "FAIL"}')

    con_a = None
    try:
        # (0) create DB via alias: per-database config is applied server-side
        with create_database(db_cfg_name, user = act.db.user, password = act.db.password) as con:
            cur = con.cursor()
            cur.execute('create table t1(id int primary key, s varchar(50))')
            cur.execute('create table burst(n int)')
            con.commit()
            tpc_block_size = cur.execute("""
                select rdb$config_value from rdb$config
                where upper(rdb$config_name) = 'TIPCACHEBLOCKSIZE'
            """).fetchone()[0]
        if int(tpc_block_size) != TPC_BLOCK_SIZE:
            pytest.skip(f"Per-database config did not apply (TipCacheBlockSize = {tpc_block_size})")
        report(f"per-database TipCacheBlockSize = {TPC_BLOCK_SIZE} applied via databases.conf", True)

        # set async write to keep the burst fast (best effort, not required for correctness):
        act.gfix(switches = ['-w', 'async', alias_dsn], combine_output = True)

        # (1) persistent attachment A: seeds data and keeps global TPC header alive
        con_a = get_conn()
        cur_a = con_a.cursor()
        cur_a.execute("insert into t1 values (1, 'original')")
        con_a.commit()
        report("attachment A committed row (1, 'original') and stays connected", True)

        # (2) attachment B: burst of autonomous transactions crossing block boundary, then detach.
        #     On buggy build B is the only user of TPC block #1 => on detach it unlinks its file.
        with get_conn() as con_b:
            con_b.cursor().execute(f"""
                execute block as
                    declare n int = {BURST_TXNS};
                begin
                    while (n > 0) do
                    begin
                        in autonomous transaction do
                            insert into burst values (:n);
                        n = n - 1;
                    end
                end
            """)
        report(f'{BURST_TXNS} autonomous transactions committed and B detached', True)

        # (3) attachment C: hard-committed UPDATE; its txn number belongs to block #1 too
        with get_conn() as con_c:
            con_c.cursor().execute("update t1 set s = 'updated_C' where id = 1")
            con_c.commit()
        report("attachment C committed UPDATE -> s = 'updated_C', detached", True)

        # (4) fresh attachment D: committed value must be visible
        with get_conn() as con_d:
            s_d = con_d.cursor().execute("select s from t1 where id = 1").fetchone()[0]
        report("fresh attachment D sees committed value 'updated_C'", s_d == 'updated_C')

        # (5) fresh attachment E (separate isql process): re-update must succeed silently.
        # NB: act.isql() raises ExecutionError if rc != 0 and expected_stderr is not set,
        # so we catch it in order to let remaining steps run and show their results:
        isql_input = f"""
            connect '{alias_dsn}' user {act.db.user} password '{act.db.password}';
            update t1 set s = 'updated_E' where id = 1;
            commit;
            quit;
        """
        isql_rc = 0
        try:
            act.isql(switches = ['-q'], connect_db = False, credentials = False, input = isql_input)
            isql_rc = act.return_code
        except Exception:
            isql_rc = 1
        if isql_rc == 0:
            report('fresh attachment E re-updated row without false conflict (isql rc=0)', True)
        else:
            err_info = ' '.join(str(act.stderr or '').split())
            report(f'fresh attachment E re-updated row without false conflict (isql rc={isql_rc}, '
                   f'isql stderr: {err_info[:300]})', False)

        # (6) fresh attachment F: must see the latest committed value
        s_f_expected = 'updated_E' if act.return_code == 0 else 'updated_C'
        with get_conn() as con_f:
            s_f = con_f.cursor().execute("select s from t1 where id = 1").fetchone()[0]
        report(f"fresh attachment F sees committed value '{s_f_expected}'", s_f == s_f_expected)

    finally:
        if con_a:
            con_a.close()

    act.expected_stdout = ''.join(f'{d}: OK\n' for d in step_descs)
    act.stdout = capsys.readouterr().out

    assert act.clean_stdout == act.clean_expected_stdout
    assert act.clean_stderr == act.clean_expected_stderr
    assert all(step_results), 'At least one check FAILED: hard-committed transaction is falsely seen as active'
