import re

import pytest
from firebird.qa import *

N_ROWS = 1000
N_WIDT = 32760

# Sizes of record headers on data pages, see src/jrd/ods.h:
# struct rhd   - common record header:             RHD_SIZE   = 13 bytes
# struct rhde  - rhd + 2 bytes of high tranum bits: RHDE_SIZE = 16 bytes
# struct rhdf  - header of fragmented record:      RHDF_SIZE  = 22 bytes
RHD_SIZE = 13
RHDF_SIZE = 22
HEADER_SIZE_DELTA = RHDF_SIZE - RHD_SIZE  # = 9: 'phantom' bytes subtracted per record by pre-fix gstat

# We allow some small deviation of 'average record length' from its exact expected
# value (e.g. because of possible minor changes in RLE encoding in future builds),
# but it must be well less than the pre-fix understatement (9 bytes per record).
ASSERT_TOLERANCE = HEADER_SIZE_DELTA / 2  # = 4.5

init_ddl = f"""
    recreate table test (f01 varchar({N_WIDT}) character set octets not null);
    commit;

    set term ^;
    execute block as
        declare n int = {N_ROWS};
    begin
        while (n > 0) do
        begin
            insert into test(f01) values( lpad('', {N_WIDT}, gen_uuid()) );
            n = n - 1;
        end
    end
    ^
    set term ;^
    commit;
"""

db = db_factory(page_size = 8192, init = init_ddl, charset = 'win1251')
act = python_act('db')

@pytest.mark.ai
@pytest.mark.version('>=5.0.5')
def test_1(act: Action, capsys):

    act.gstat(switches=['-r', '-t', 'TEST'])

    # Average record length: 32766.00, total records: 1000
    p_average_record_length = re.compile( r'Average\s+record\s+length(:)?\s+(\d+(.\d+)?)(,)?\s+total\s+records(:)?\s+(\d+)' )

    # Average unpacked length: 32766.00, compression ratio: 1.00
    p_average_unpacked_length = re.compile( r'Average\s+unpacked\s+length(:)?\s+(\d+(.\d+)?)(,)?\s+compression\s+ratio(:)?\s+(\d+(.\d+)?)' )

    # Average fragment length: 8144.25, total fragments: 4000, max fragments: 4
    p_fragment_stats = re.compile( r'Average\s+fragment\s+length(:)?\s+(\d+(.\d+)?)(,)?\s+total\s+fragments(:)?\s+(\d+)(,)?\s+max\s+fragments(:)?\s+(\d+)' )

    m_rec = p_average_record_length.search(act.stdout)
    m_unp = p_average_unpacked_length.search(act.stdout)
    m_frg = p_fragment_stats.search(act.stdout)

    assert m_rec, f'missing gstat line matching pattern {p_average_record_length.pattern}. Actual gstat stdout:\n{act.stdout}'
    assert m_unp, f'missing gstat line matching pattern {p_average_unpacked_length.pattern}. Actual gstat stdout:\n{act.stdout}'
    assert m_frg, f'missing gstat line matching pattern {p_fragment_stats.pattern}. Actual gstat stdout:\n{act.stdout}'

    average_record_length = float(m_rec.group(2))
    total_records = int(m_rec.group(6))

    average_unpacked_length = float(m_unp.group(2))
    compression_ratio = float(m_unp.group(6))

    average_fragment_length = float(m_frg.group(2))
    total_fragments = int(m_frg.group(6))
    max_fragments = int(m_frg.group(9))

    # Sanity checks that scenario works as intended:
    # * all records have been stored, and each of them is fragmented (no record can fit on 8192 page);
    # * compression ratio = 1.00 means that packed data does not compress, i.e. average record
    #   length must be EQUAL to average unpacked length rather than be less than it.
    assert total_records >= N_ROWS
    assert total_fragments >= N_ROWS and max_fragments >= 2, f'expected all records to be fragmented, got: total_fragments={total_fragments}, max_fragments={max_fragments}'
    assert compression_ratio > 0.99 and compression_ratio <= 1.01, f'expected incompressible data (ratio ~ 1.00), got: compression_ratio={compression_ratio}'

    #-------------------------------------------------------------------------------------------
    msg_scenario_expected = f'gstat accounts ALL fragments: total_fragments={total_fragments} >= N_ROWS={N_ROWS}, max_fragments={max_fragments} >= 2'

    if total_fragments >= N_ROWS and max_fragments >= 2:
        print(msg_scenario_expected)
    else:
        print('gstat scenario check -- UNEXPECTED: some records are not fragmented, see assert above')

    #-------------------------------------------------------------------------------------------
    # MAIN CHECK: gstat must not understate 'average record length' by the size of
    # last fragment header. Pre-fix gstat subtracts RHDF_SIZE (22) from EVERY fragment
    # including the last one which is stored with RHD_SIZE (13), thus every fragmented
    # record loses exactly HEADER_SIZE_DELTA = 9 bytes.
    msg_avg_rec_len_expected = f'EXPECTED: {average_record_length=} EQUAL (within +/- {ASSERT_TOLERANCE=}) to {average_unpacked_length=}'

    # befo fix: average_unpacked_length=32766.0, average_record_length=32757.0 ; abs(diff) = 9
    # afte fix: average_unpacked_length=32766.0, average_record_length=32766.0 ; abs(diff) = 0
    size_diff = abs(average_unpacked_length - average_record_length)
    if size_diff < ASSERT_TOLERANCE:
        print(msg_avg_rec_len_expected)
    else:
        print(f'UNEXPECTED: {average_record_length=} differs from {average_unpacked_length=} by {size_diff=} bytes >= {ASSERT_TOLERANCE=}')
        print(f'(pre-fix gstat understates packed record size by {HEADER_SIZE_DELTA=} bytes per each fragmented record)')

    act.expected_stdout = f"""
        {msg_scenario_expected}
        {msg_avg_rec_len_expected}
    """
    act.stdout = capsys.readouterr().out
    assert act.clean_stdout == act.clean_expected_stdout
