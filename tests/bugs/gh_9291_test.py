"""
ID:          issue-9291
ISSUE:       https://github.com/FirebirdSQL/firebird/issues/9291
TITLE:       gbak omits the exact final record count from backup logs
DESCRIPTION:
    [generated by zcode.ai]
    GBak backup which runs with '-verbint <n>' option reports number of records for each processed portion of data, msg 108:
    "@1 records written".
    BackupRelationTask::fileWriter() (src/burp/BurpTasks.cpp) stored in 'verbRecs' the ACTUAL number of records that were
    processed at the moment when reporting threshold was hit last time, whereas the message itself reported the value rounded DOWN
    to the multiple of verbose interval:
        verbRecs = records;
        BURP_verbose(108, SafeArg() << (verb * tdgbl->verboseInterval));
    Because of that the final check 'if (records != verbRecs)' could skip issuing the final message with exact total: backup of a
    table with 101 records and '-verbint 100' ended in the log with '100 records written' (see description of issue #9291 which is
    fixed by PR #9292, commit a68b20a).
    Fix aligns 'verbRecs' with the reported rounded value:
        verbRecs = verb * tdgbl->verboseInterval;
    so the final check emits the exact total whenever it differs from the last reported portion of data.

    TEST_PLAN:
    1. Create a table with 101 records of small size: all of them are expected to be placed into the single IO buffer during
       backup (backup IO buffer is at least 128 KB, see MIN_IO_BUFFER_SIZE in src/burp/BurpTasks.cpp), so the last processed
       buffer crosses the reporting threshold 100 and contains the total number of records (101) which is not a multiple of
       verbose interval.
    2. Backup the database with '-verbint 100 -parallel 1'. Switch '-verbint' implies verbose mode (burp.cpp:
       'if (verbint) tdgbl->gbl_sw_verbose = true;'), '-parallel 1' ensures the single-writer mode, so all the records are counted
       by fileWriter() in one pass and reporting is deterministic.
    3. Parse gbak output and collect all "records written" messages which relate to the tested table (they follow the line
       "writing data for table/relation <name>" - msg 142 - and precede the next such line).
    4. Assert that the log contains BOTH the threshold report (100) AND the final exact count (101), i.e. the last reported number
       is exactly 101.

    Before the fix backup log ended with '100 records written' and no final message with exact count (101) was issued.
NOTES:
    [13.11.2026] pzotov
    Test was generated by zcode.ai.
    Confirmed bug on 6.0.0.2455-850887f (build without fix).
    Checked on 6.0.0.2463-b8c2a6a (build with fix).
"""

import locale
import re
from pathlib import Path
import pytest
from firebird.qa import *

db = db_factory()
act = isql_act('db', """
    recreate table test_9291(id smallint);
    commit;
    insert into test_9291
    with recursive n(n) as (
        select 1 from rdb$database
        union all
        select n.n + 1 from n where n.n < 101
    )
    select n from n;
    commit;
""")

tmp_fbk = temp_file('gh_9291.tmp.fbk')

table_name = 'test_9291'
row_count = 101
verbose_interval = 100

@pytest.mark.version('>=5.0')
@pytest.mark.ai
def test_1(act: Action, tmp_fbk: Path, capsys):

    act.execute()

    act.gbak(switches=['-b', '-verbint', str(verbose_interval), '-parallel', '1',
                       act.db.dsn, str(tmp_fbk)],
             combine_output = True,
             io_enc = locale.getpreferredencoding())
    assert act.return_code == 0

    # FB 6.x: msg 142 text is "writing data for table <name>" where name is
    # schema-qualified, e.g.: 'writing data for table "PUBLIC"."TEST_9291"'.
    section_re = re.compile(r'writing\s+data\s+for\s+(?:table|relation)\s+(.*\S)', re.IGNORECASE)
    counts_re = re.compile(r'(\d+)\s+records\s+written', re.IGNORECASE)

    tbl_counts = []
    cur_table = None
    for line in act.clean_stdout.splitlines():
        m = section_re.search(line)
        if m:
            cur_table = m.group(1).split('.')[-1].strip().strip('"').upper()
            continue
        m = counts_re.search(line)
        if m and cur_table == table_name.upper():
            tbl_counts.append(int(m.group(1)))

    assert tbl_counts, f"No 'records written' messages found for table {table_name} in backup log"

    for cnt in tbl_counts:
        print('records written (reported for tested table):', cnt)

    print(f'last record count in backup log: {tbl_counts[-1]} (expected: {row_count})', 'OK' if tbl_counts[-1] == row_count else 'MISMATCH')

    act.reset()
    act.expected_stdout = f"""
        records written (reported for tested table): {verbose_interval}
        records written (reported for tested table): {row_count}
        last record count in backup log: {row_count} (expected: {row_count}) OK
    """
    act.stdout = capsys.readouterr().out
    assert act.clean_stdout == act.clean_expected_stdout
