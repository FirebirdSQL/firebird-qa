"""
ID:          n/a
ISSUE:       https://github.com/FirebirdSQL/firebird/issues/8012
TITLE:       SELECT crashes the server when LIST(DISTINCT (SELECT ...)) is used as a GROUP BY item
DESCRIPTION:
    [text was generated by zcode.ai]
    Two defects in the DSQL scope-checking code allowed an aggregate to escape the check
    "aggregate must not appear in the GROUP BY / WHERE clause" and to be passed further with
    no sort block being allocated for it. AggNode::execute() then dereferenced the NULL
    pointer (asb), which crashed the server ('Access violation' in firebird.log).

    Beside crashes, both defects also allowed INVALID queries to be silently accepted
    (cases A6, B7, C1: non-DISTINCT aggregate in the GROUP BY list / undetected nested aggregate),
    and made the intermediate build with 61cce64 only to lose the proper rejection for
    cases B8 and C2 (per the reporter's analysis in the ticket, see comments of 05.11.2026).
    Test consists of two parts:
      * negative cases A1-A8, B1-B20, C1-C2: each of them must be rejected at PREPARE time
        with SQLSTATE = 42000 (see expected output for the exact message of every case).
        Beside plain EXISTS / IN / SINGULAR / ALL / ANY, cases B10-B20 cover combined and
        negated predicates, a predicate whose operand is a scalar sub-select, a predicate
        inside a sub-select, a recursive CTE member (its own error message) and a
        hypothetical-set aggregate;
      * positive cases P1-P26: valid queries which mix aggregates with sub-selects and
        outer references. They must continue to work and return unchanged data (they do
        return the same values both on broken and on fixed builds, see NOTES).
        Cases P11-P26 add, among others: a field of the checked block as the left operand
        of IN, such aggregates in GROUP BY / HAVING / ORDER BY context and inside
        sub-selects, and a window function with a predicate sub-select in its argument.
    Commits that fixed the problem:
        6.x: https://github.com/FirebirdSQL/firebird/commit/61cce64a4ae7a1c3abaf3928093bbd2221a94040
             https://github.com/FirebirdSQL/firebird/commit/77d81859c2c3ac98dcaf2b6f6183dab61c24a41d
NOTES:
    [07.11.2026] pzotov
    Test was generated by AI (ZCode / GLM).
    Based on the prototype provided in the ticket by dimitr:
        https://github.com/user-attachments/files/34422838/gh_8012_test.py
    Extended with the whole family of predicate-with-sub-select cases (B1-B9) that was fixed
    by the postfix commit 77d8185 and was NOT covered by the prototype.

    ACHTUNG: negative cases are only PREPARED here, never executed. On a fixed build the
    rejection happens exactly at prepare time, while the crash itself occurs at execution
    time (AggNode::execute() with asb == NULL). Because negative statements are not executed,
    this test does NOT kill the server on a broken build: every case that must be rejected
    is silently accepted at prepare instead, and the test fails showing
    'NO ERROR RAISED - QUERY WAS ACCEPTED!' for each such case (confirmed on 5.0.5.1902
    and 6.0.0.2210 via pytest: cases A1-A6, A8, B1-B7 and C1 are accepted, whereas A7, B8,
    B9 and C2 are rejected with the same messages as on the fixed build, and all positive
    cases return expected values).
    LIST() returns BLOB SUB_TYPE TEXT, hence its value is cast to VARCHAR in positive cases
    in order to avoid printing of blob ids.

    Added cases B10-B20 and P11-P26 which are taken from the extended test (gh_8012_test.py,
    its test_script_3 / test_script_4), so that every shape mentioned there is covered here too.
    Case B12 exercises RseBoolNode::convertNeqAllToNotAny(); case B19 is rejected with its own
    message (see ERR_RECURSIVE); case B20 (percentile_cont ... within group (order by (select ...)))
    is also affected by commit 871e33ce, hence its expected GROUP BY error holds only on builds
    which include that commit too (version gate of this test is '>=6.0').

    Required result:
        * all negative cases raise SQLSTATE = 42000 at prepare;
        * all positive cases return expected data;
        * firebird.log remains empty
    Checked on 6.0.0.2452-871e33c.
"""

