@pytest.mark.ai
@pytest.mark.version('>=6.0')
def test_1(act: Action, capsys):

    with act.db.connect() as con:
        cur = con.cursor()

        # Part 1: each query must be rejected at prepare time with SQLSTATE = 42000:
        for cid, note, chk_sql, err_msg in neg_cases:
            print(f'### {cid}: {note}')
            print(chk_sql)
            ps, rs = None, None
            try:
                ps = cur.prepare(chk_sql)
                print('NO ERROR RAISED - QUERY WAS ACCEPTED!')
            except DatabaseError as e:
                msg_last = [l for l in e.__str__().splitlines() if l.strip()][-1].lstrip('- ').rstrip()
                print(f'SQLSTATE = {e.sqlstate}')
                print(msg_last)
            finally:
                if rs:
                    rs.close()
                if ps:
                    ps.free()
            print('')

        # Part 2: valid queries must keep working and return unchanged data:
        for cid, note, chk_sql, exp_rows in pos_cases:
            print(f'### {cid}: {note}')
            print(chk_sql)
            ps, rs = None, None
            try:
                ps = cur.prepare(chk_sql)
                # ::: NB ::: 'ps' returns data, i.e. this is SELECTABLE expression.
                # We have to store result of cur.execute(<psInstance>) in order to
                # close it explicitly (explained by hvlad, email 26.10.24 17:42).
                rs = cur.execute(ps)
                cur_cols = cur.description
                for r in cur:
                    for i in range(len(cur_cols)):
                        print( f'{cur_cols[i][0]} : {r[i]}' )
            except DatabaseError as e:
                print(e.__str__())
                raise
            finally:
                if rs:
                    rs.close() # <<< EXPLICITLY CLOSING CURSOR RESULTS
                if ps:
                    ps.free()
            print('')

    exp_lines = []
    for cid, note, chk_sql, err_msg in neg_cases:
        exp_lines += [f'### {cid}: {note}', chk_sql, 'SQLSTATE = 42000', err_msg, '']
    for cid, note, chk_sql, exp_rows in pos_cases:
        exp_lines += [f'### {cid}: {note}', chk_sql, *exp_rows, '']
    act.expected_stdout = '\n'.join(exp_lines)

    act.stdout = capsys.readouterr().out
    assert act.clean_stdout == act.clean_expected_stdout
