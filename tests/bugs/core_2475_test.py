from pathlib import Path
import pytest
from firebird.qa import *
from firebird.driver import connect as drv_connect, tpb, Isolation, TraAccessMode

# Name of alias that will be written into temporary replacement of databases.conf:
CONNECT_TO_ALIAS = 'tmp_core_2475_alias'

# name of external table that will be used in SQL statements:
EXT_TABLE_NAME = 'ext_test_2475'

db = db_factory()

act = python_act('db')

custom_tpb = tpb( access_mode = TraAccessMode.WRITE,
                  isolation = Isolation.READ_COMMITTED_RECORD_VERSION,
                )

@pytest.mark.ai
@pytest.mark.version('>=3.0')
def test_1(act: Action, store_config: ConfigManager):

    if act.vars['server-arch'].lower() != 'classic':
        pytest.skip('Applies only to Classic')

    # Obtain the physical database location.
    # NOTE: we must NOT use 'act.db.db_path' for ALIASED databases! It will return '.' rather than full path+filename.
    # Use only con.info.name for that:
    TEMP_DB_CONF_CONTENT = ''
    with act.db.connect() as con:
        test_db_file = con.info.name
        test_db_path = Path(test_db_file).parent
        TEMP_DB_CONF_CONTENT = f"""
            {CONNECT_TO_ALIAS} = {test_db_file}
            {{
                ExternalFileAccess = Restrict {test_db_path}
            }}
        """
    assert CONNECT_TO_ALIAS in TEMP_DB_CONF_CONTENT and 'ExternalFileAccess' in TEMP_DB_CONF_CONTENT

    # REPLACE databases.conf:
    store_config.replace('databases.conf', TEMP_DB_CONF_CONTENT)

    # Storage of external table will be in the SAME directory as test DB uses:
    ext_file = test_db_path / 'c2475.dat'

    # Remove leftovers from an interrupted/failed previous test run.
    ext_file.unlink(missing_ok=True)

    external_file = str(ext_file).replace("'", "''")

    # Create external table, connect by ALIAS:
    act.expected_stdout = ''

    test_script = f"""
        set bail on;
        connect 'localhost:{CONNECT_TO_ALIAS}' user {act.db.user} password '{act.db.password}';
        create table {EXT_TABLE_NAME} external file '{external_file}'(pk integer, lf char(1));
        commit;
    """
    act.isql(switches=['-q'], connect_db = False, credentials = False, input = test_script, combine_output = True)

    # isql must not produce any output here:
    assert act.clean_stdout == act.clean_expected_stdout
    act.reset()

    # 1) initial check (issue #2888): data must be visible to another CONNECTION ("session B"):
    with drv_connect(database = f'localhost:{CONNECT_TO_ALIAS}', user = act.db.user, password = act.db.password) as con_a, \
         drv_connect(database = f'localhost:{CONNECT_TO_ALIAS}', user = act.db.user, password = act.db.password) as con_b:
        cur_a = con_a.cursor()
        cur_b = con_b.cursor()

        cur_a.execute(f"insert into {EXT_TABLE_NAME} (pk, lf) values (1, ascii_char(10))")
        con_a.commit()

        cur_b.execute(f'select pk from {EXT_TABLE_NAME}')
        result = cur_b.fetchall()

    assert result == [(1, )]

    # 2) added check: data must be visible to another TRANSACTION that belongs to the same connection:
    with drv_connect(database = f'localhost:{CONNECT_TO_ALIAS}', user = act.db.user, password = act.db.password) as con:

        tx1 = con.transaction_manager(custom_tpb)
        tx1.begin()
        tx2 = con.transaction_manager(custom_tpb)
        tx2.begin()

        cur1 = tx1.cursor()
        cur2 = tx2.cursor()

        cur1.execute(f"insert into {EXT_TABLE_NAME} (pk, lf) values (2, ascii_char(10))")
        tx1.commit()

        cur2.execute(f'select pk from {EXT_TABLE_NAME} order by pk')
        tx_rows = cur2.fetchall()
        tx2.rollback()

    assert tx_rows == [(1,), (2,)]

    ext_file.unlink(missing_ok = True)
