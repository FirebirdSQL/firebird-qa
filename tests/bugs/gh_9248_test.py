#-------------------------------------------------------------------------------------------
def run_in_new_tx(con, sql: str):
    """Run statement in a new RC/RV transaction and commit it.
    Returns list of fetched rows (None if statement returns no data),
    or string 'ERROR: <message from engine>' if statement failed.
    """
    tra = con.transaction_manager(tra_tpb)
    tra.begin()
    cur = tra.cursor()
    try:
        cur.execute(sql)
        rows = cur.fetchall() if cur.description else None
        cur.close()
        tra.commit()
        return rows
    except DatabaseError as e:
        tra.rollback()
        return 'ERROR: ' + ' '.join(x.strip() for x in str(e).splitlines())

#-------------------------------------------------------------------------------------------
def insert_returning_val(con, id_value: int):
    """Insert one row into table 'test' in a new RC/RV transaction; return formatted result:
    either 'VAL = <x>' or 'ERROR: <message from engine>'.
    """
    res = run_in_new_tx(con, f'insert into test (ID) values ({id_value}) returning VAL')
    return res if isinstance(res, str) else f'VAL = {res[0][0]}'

