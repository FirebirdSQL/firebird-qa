"""
ID:          n/a
ISSUE:       https://github.com/FirebirdSQL/firebird/pull/9108
TITLE:       Convert string literals to the operand type at prepare time in comparisons
DESCRIPTION:
    Test creates table with fields of datatypes psecified in the ticket: double, decfloat(16/34), int128, date, time[with TZ], timestamp[with TZ]
    Then it adds <TEST_ROWS_CNT> into it with random not-null data.
    At some iteration (random, from scope 1...TEST_ROWS_CNT) generated values are saved also in auxiliary table (AUX_DATA).
    These values will be used further as LITERALS and EXECUTE STATEMENT PARAMETERS in the queries that will be checked.
    For example, following queries will use same timestamp with TZ as literal and parameter:
       Q1: select count(*) from test  where tstz is not distinct from '2026-08-19 05:35:40.0000 Asia/Urumqi'
       Q2: execute block returns(cnt int) as begin execute statement ('select count(*) from test where tstz is not distinct from ?') ('2026-08-19 05:35:40.0000 Asia/Urumqi') into cnt; suspend; end
    Test will compare values returned by Q1 and Q2: they must be equal.
    Check is repeated for cases when table has no indices and then when each column is indexed using regular, partial and computed index -- see func 'add_indices'.
NOTES:
    [14.08.2026] pzotov
    Performance slowdown detected for some cases, see: https://github.com/FirebirdSQL/firebird/pull/9108#issuecomment-5276992625
    Test may be supplemented later with measurement of CPU cycles for each performing pair of queries and comparing their ratio with some threshold.
    Checked on 6.0.0.2143-81cfcf9.
"""

