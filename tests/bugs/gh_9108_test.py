#-------------------------------------------------------

def add_indices(mode, con):

    idx_lst = []
    sql_fields_lst = "select trim(rdb$field_name) from rdb$relation_fields rf where rf.rdb$relation_name = upper('test') and rf.rdb$field_name <> upper('id')"
    cur = con.cursor()
    cur.execute(sql_fields_lst)
    for r in cur:
        idx_direction = 'ascending' if random.random() < 0.5 else 'descending'
        idx_name = f'test_{r[0]}_{mode}_{idx_direction}'
        idx_suff = ''
        if mode == 'index_regular':
           idx_suff = f' ({r[0]})'
        elif mode == 'index_partial':
           idx_suff = f' ({r[0]}) where {r[0]} is not null'
        elif mode == 'index_computed':
           idx_suff = f' computed by ({r[0]})'

        idx_lst.append(idx_name)
        con.execute_immediate(f"create {idx_direction} index {idx_name} on test {idx_suff}")
    con.commit()

    return idx_lst

