@pytest.mark.ai
@pytest.mark.perf_measure
@pytest.mark.version('>=6.0')
def test_1(act: Action, tmp_fdb: Path, capsys, request):

    if 'classic' in act.vars['server-arch'].lower():
        pytest.skip('Implemented only for SS/SC')

    echo_lines = []
    def echo(s: str) -> None:
        # Data that is captured by capsys (and by pytest global capture too)
        # is displayed only in case of test FAIL. To make measured values
        # visible in the log regardless of test outcome, we register tiny
        # plugin that will print them in the terminal summary - it is written
        # when test session ends, i.e. when capture is already disabled.
        #
        # In verification mode (MAX_RATIO >= 0) these values are needed only
        # when the threshold is violated, i.e. on FAIL - on PASS they are
        # suppressed. In report-only mode (MAX_RATIO < 0) they are printed
        # always, as otherwise they can not be seen anywhere.
        if MAX_RATIO >= 0 and median_ratio <= MAX_RATIO:
            return
        echo_lines.append(s)
        if not request.config.pluginmanager.has_plugin('gh_9131_echo'):
            class EchoPlugin:
                @pytest.hookimpl(trylast = True)
                def pytest_terminal_summary(self, terminalreporter, exitstatus, config):
                    terminalreporter.write_sep('=', 'gh_9131: measured CPU times')
                    for ln in echo_lines:
                        terminalreporter.write_line(ln)
            request.config.pluginmanager.register(EchoPlugin(), 'gh_9131_echo')

    srv_cfg = driver_config.register_server(name = 'test_srv_gh_9131', config = '')
    # NOTE: host and port must be set EXPLICITLY. If server config is left
    # empty, _connect_helper() builds DSN as 'inet://<path>' with no host and
    # port, and the connection is routed not to the instance being tested but
    # by fbclient fallback rules (XNET / default port).
    srv_cfg.host.value = act.vars['host'] or 'localhost'
    if act.vars['port']:
        srv_cfg.port.value = str(act.vars['port'])

    db_cfg_name = 'tmp_gh_9131_create'
    db_cfg_object = driver_config.register_database(name = db_cfg_name)
    db_cfg_object.server.value = srv_cfg.name
    db_cfg_object.protocol.value = NetProtocol.INET
    db_cfg_object.database.value = str(tmp_fdb)
    # Minimal page size: do not spend CPU for page formatting on data that
    # is identical for both builds, see DESCRIPTION p.2:
    db_cfg_object.page_size.value = 4096
    db_cfg_object.forced_writes.value = True

    with act.db.connect() as con:
        cur = con.cursor()
        cur.execute('select mon$server_pid from mon$attachments where mon$attachment_id = current_connection')
        fb_pid = int(cur.fetchone()[0])

    fb_proc = psutil.Process(fb_pid)

    def burn_client_cpu() -> tuple:
        # Pure client-side calculations, no DB access at all.
        h = hashlib.sha512()
        c0 = _get_process_cycles(os.getpid()) if os.name == 'nt' else 0
        t0 = time.process_time()
        for _ in range(N_HASH_ITERATIONS):
            h.update(HASH_BUF)
        t1 = time.process_time()
        c1 = _get_process_cycles(os.getpid()) if os.name == 'nt' else 0
        return (max(t1 - t0, 0.000001), max(c1 - c0, 1))

    def create_db() -> tuple:
        tmp_fdb.unlink(missing_ok = True)
        c0 = _get_process_cycles(fb_pid) if os.name == 'nt' else 0
        t0 = fb_proc.cpu_times()
        with create_database(db_cfg_name, user = act.db.user, password = act.db.password,
                             overwrite = True, charset = 'utf8') as dbc:
            pass
        t1 = fb_proc.cpu_times()
        c1 = _get_process_cycles(fb_pid) if os.name == 'nt' else 0
        tmp_fdb.unlink(missing_ok = True)
        return (max(t1.user - t0.user, 0.000001), max(c1 - c0, 1))

    # warm-up: engine code pages, ICU library, client DLL internals etc:
    burn_client_cpu()
    create_db()

    cpu_burn_vals = []
    cpu_burn_cycles = []
    db_create_vals = []
    db_create_cycles = []

    for _ in range(N_MEASURES):
        # alternate samples to keep thermal / turbo state similar for D and M:
        v, c = burn_client_cpu()
        cpu_burn_vals.append(v)
        cpu_burn_cycles.append(c)
        v, c = create_db()
        db_create_vals.append(v)
        db_create_cycles.append(c)

    db_create_median = median(db_create_vals)
    cpu_burn_median = median(cpu_burn_vals)
    median_ratio = db_create_median / cpu_burn_median

    ratio_str = 'acceptable' if MAX_RATIO < 0 or median_ratio <= MAX_RATIO else \
                '/* perf_issue_tag */ POOR: %s, more than threshold: %s' % \
                ( '{:9g}'.format(median_ratio), '{:9g}'.format(MAX_RATIO) )
    print( 'Medians ratio: ' + ratio_str )
    medians_str = (f'db_create_median = {db_create_median:.6f} '
                   f'cpu_burn_median = {cpu_burn_median:.6f} '
                   f'median_ratio = {median_ratio:.6f}')
    print(medians_str)
    echo(medians_str)

    if os.name == 'nt':
        db_create_median_cycles = median(db_create_cycles)
        cpu_burn_median_cycles = median(cpu_burn_cycles)
        cycles_ratio = db_create_median_cycles / cpu_burn_median_cycles
        cycles_str = (f'db_create_median_cycles = {db_create_median_cycles} '
                      f'cpu_burn_median_cycles = {cpu_burn_median_cycles} '
                      f'cycles_ratio = {cycles_ratio:.6f}')
        print(cycles_str)
        echo(cycles_str)

    if MAX_RATIO >= 0 and median_ratio > MAX_RATIO:
        print(f'CPU times for each of {N_MEASURES} measures:')
        for sp_name, vals in ( ('db_create', db_create_vals), ('cpu_burn', cpu_burn_vals) ):
            print(f'{sp_name=}:')
            for p in vals:
                print(p)

    # Numbers in output vary from run to run, so they are replaced by
    # placeholder during output cleaning:
    act.substitutions = [ ( r'(?<== )[0-9]+(\.[0-9]+)?', '<NUM>' ) ]
    act.expected_stdout = expected_stdout
    act.stdout = capsys.readouterr().out
    assert act.clean_stdout == act.clean_expected_stdout
