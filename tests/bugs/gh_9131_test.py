if os.name == 'nt':
    _PROCESS_QUERY_LIMITED_INFORMATION = 0x1000
    def _get_process_cycles(pid: int) -> int:
        # Resolution of QueryProcessCycleTime is far better than 1/64 s
        # granularity of GetProcessTimes / psutil cpu_times().
        h = ctypes.windll.kernel32.OpenProcess(_PROCESS_QUERY_LIMITED_INFORMATION, False, pid)
        cycles = ctypes.c_ulonglong()
        try:
            ctypes.windll.kernel32.QueryProcessCycleTime(h, ctypes.byref(cycles))
        finally:
            ctypes.windll.kernel32.CloseHandle(h)
        return cycles.value
else:
    def _get_process_cycles(pid: int) -> int:
        return 0

